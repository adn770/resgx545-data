"""guard_blobs.py [--root DIR]: the laptop limits applied to the ASSEMBLED code of the blob and to every table of R5-events (R4-events'
guard_blobs.py with ring_hold and ring_exit2 dropped, the blob pinned to R4's bytes and the clock values checked).
Exit 0 clean, 1 with one `GUARD:` line a finding.  Run by run/guard_r4e.sh; the tests feed it bad blobs and bad tables.

What it checks:
  * each bins/NAME.blob is exactly what asm/NAME.s assembles to (the landed `fwtask.build_blob_text`, which runs the landed verifier) and the
    source's instructions (the landed `own_end` macro expanded to its two words) are the blob's words, one for one;
  * ring_skip3p is R4-events' bytes (sha256 pinned in r5layout.SKIP3P_SHA);
  * NO firmware `str` in any blob (R4-7: 0x0814 and 0x0a78 only, and this session needs none); `ldr` only of register #81 (CR_TIMER); no `mov`
    to a pa register; no write to an sa register, r20, r21 or an i register; pclink only by the patched continue triples (one an entry);
    no `cont4` patch;
  * the exit's own words: the cache flush `cfi.global` nowhere; the phase end `phas #0, #0, pixel, end, parallel` exactly once, in block
    endp (ring_exit2) or end3 (ring_skip3p), preceded by idf and wdf and followed by nop.end; none in ring_hold; the landed lint
    (`fwtask.lint`) is clean for the two new sources;
  * the tables are exactly the rows of r5layout.ROW_SPEC (regenerated by gen/gen_r5.py and compared); arm lines from the allow-list;
    no trc, no kpoke, no clock-gate register in a table; the only values ever written to the clear register are CLEAR (0x0134) bits 15
    and 18; timer_clock only 0, 800000, 1600000 (r5layout.CLOCKS); hold_recovery Y exactly in the skipped rows.
"""
import json
import pathlib
import re
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
R5 = HERE.parent
sys.path.insert(0, str(R5 / "gen"))
import r5layout as L  # noqa: E402
import r3blobs as B  # noqa: E402
import gen_r5 as GEN  # noqa: E402

fw = B.fwtask
TEMP_MASK = (0x1FF << 21) | (1 << 51)
ARMS = {a for a in L.ARM_OF.values() if a}
ROWS = {st: set(rows) for st, rows in L.ROW_SPEC.items()}
BLOB_OF = L.BLOB_OF
BLOBS = L.BLOBS
EXIT_CFI, EXIT_PHAS = 0xF843B300A0000180, 0xFA44070000000000
OWN_BLOCK = {"ring_skip3p": "end3"}
LINTED = ("ring_skip3p",)


def _ref():
    ref = {}
    for bank, base in (("r", 0), ("sa", 0), ("i", 124)):
        for n in range(128 if bank != "i" else 4):
            try:
                w = fw.assemble_text(f"mov {bank}{n}, r11")[0]
            except Exception:
                continue
            ref.setdefault(w & TEMP_MASK, ("r" if bank == "i" else bank, n + base))
    return ref


REF = _ref()


def dest_of(w):
    d = REF.get(w & TEMP_MASK)
    if d is None:
        return ("unknown",)
    bank, n = d
    if bank == "sa":
        return ("sa", n)
    if n in (20, 21):
        return (f"r{n}",)
    if n >= 124:
        return ("i", n - 124)
    return ("temp", n)


def instructions(text):
    """The instruction lines in word order, the landed `own_end` macro expanded (two words)."""
    out = []
    for s in B.instructions(text):
        out += list(fw.OWN_END) if s == "own_end" else [s]
    return out


def label_ranges(text):
    """{label: (first word index, last + 1)}; a label runs to the next label."""
    idx, cur, out = 0, None, {}
    for _, lab, s in B.code_lines(text):
        if lab:
            if cur is not None:
                out[cur] = (out[cur][0], idx)
            cur = lab
            out[cur] = (idx, idx)
        elif not s.startswith("@"):
            idx += 2 if s == "own_end" else 1
    if cur is not None:
        out[cur] = (out[cur][0], idx)
    return out


def check_blob(name, text, blob, regs=None):
    """Problems of one blob."""
    regs = regs or fw.load_regs()
    out = []
    try:
        if fw.build_blob_text(text, regs) != blob:
            out.append(f"{name}: the blob is not what its source assembles to")
    except fw.VerifyError as e:
        return out + [f"{name}: the landed verifier refuses the source: {e}"]
    try:
        bad = fw.verify_blob(blob, regs)
    except Exception as e:
        bad = [repr(e)]
    if bad:
        out.append(f"{name}: the landed verifier refuses the blob: {bad[:2]}")
    pb = fw.parse_blob(blob)
    words = pb.words
    lines = instructions(text)
    rng = label_ranges(text)
    if len(lines) != len(words):
        return out + [f"{name}: source has {len(lines)} instructions, the blob {len(words)} words"]
    pclink = 0
    for i, w in enumerate(words):
        kind, _nm = fw.classify(w)
        if kind == "STR":
            out.append(f"{name}: word {i}: a firmware str (register #{fw.reg_index(w)}): this session carries none ({lines[i]})")
        elif kind == "LDR":
            if fw.reg_index(w) != 81:
                out.append(f"{name}: word {i}: ldr of register #{fw.reg_index(w)}; only #81 (CR_TIMER) is allowed")
        elif kind == "MOVPCLINK":
            pclink += 1
        elif kind == "MOVPA":
            out.append(f"{name}: word {i}: a mov to a pa register ({lines[i]})")
        elif kind == "MOVREG":
            d = dest_of(w)
            if d[0] in ("sa", "r20", "r21", "i", "unknown"):
                out.append(f"{name}: word {i}: a register move to {d} ({lines[i]})")
        if w == EXIT_CFI:
            out.append(f"{name}: word {i}: the exit's cfi.global: no blob of this session carries it")
    if pclink != len(pb.entries):
        out.append(f"{name}: {pclink} pclink writes for {len(pb.entries)} entries (only the continue triples: once an entry)")
    kinds = sorted(p.kind for p in pb.patches if p.kind.startswith("cont"))
    if kinds != sorted(f"cont{k}" for k in range(len(pb.entries))):
        out.append(f"{name}: continue patches {kinds}")
    if any(p.kind == "cont4" for p in pb.patches):
        out.append(f"{name}: a cont4 patch (the real exit): none of this session's blobs carries one")
    phas = [i for i, w in enumerate(words) if w == EXIT_PHAS]
    if name in OWN_BLOCK:
        a = rng.get(OWN_BLOCK[name], (0, 0))[0]          # the block is idf, wdf, phas end, nop.end (4 words; the label runs on to the next one)
        if phas != [a + 2]:
            out.append(f"{name}: the phase end is at {phas}, not once at word {a + 2} of block {OWN_BLOCK[name]}")
        elif not (lines[a].startswith("idf ") and lines[a + 1].startswith("wdf ") and fw.classify(words[a + 3])[0] == "NOP"):
            out.append(f"{name}: block {OWN_BLOCK[name]} is not idf, wdf, phas end, nop.end")
        if name in LINTED and fw.lint(text):
            out.append(f"{name}: the landed lint warns: {fw.lint(text)[:1]}")
    elif phas:
        out.append(f"{name}: carries the phase end at {phas}: only ring_skip3p may")
    return out


FORBIDDEN_TABLE = re.compile(r"\btrc\b|trc_hazard|kreg(?!now)|kpoke|alias_skip|clkgate|CLKGATE|xfer|bare|0x0c00|0x0c04|0x0114|CLEAR2|kicker")


def check_rowspec():
    """The frozen values of r5layout.ROW_SPEC itself: what may ever be written to a register or a knob."""
    out = []
    if tuple(L.H_CLEAR_VALUES) != (0x8000, 0x40000):
        out.append(f"r5layout.H_CLEAR_VALUES {L.H_CLEAR_VALUES} is not bits 15 and 18")
    if tuple(L.CLOCKS) != (0, 800000, 1600000):
        out.append(f"r5layout.CLOCKS {L.CLOCKS} is not the approved 0, 800000, 1600000")
    if L.STR_OF:
        out.append("r5layout.STR_OF is not empty: this session carries no firmware str")
    for st, rows in L.ROW_SPEC.items():
        for row, spec in rows.items():
            if spec["op"] not in L.STAGE_INFO[st]["ops"]:
                out.append(f"{st}/{row}: op {spec['op']} is not allowed in this stage")
            if spec["skip"] not in (0, 1) or spec["timer_clock"] not in L.CLOCKS or spec["clears"] not in ("none", "late", "early"):
                out.append(f"{st}/{row}: skip, clock or clears off the allow-list")
            if bool(spec["may_stop"]) != bool(spec["skip"]):
                out.append(f"{st}/{row}: only a skipped row may stop")
    return out


def check_tables(tables):
    """Problems of the job tables ({stage: table}) against r5layout.ROW_SPEC (the tables regenerated from it are compared whole)."""
    out = check_rowspec()
    for st, t in tables.items():
        if t.get("stage") != st or t.get("blob") != BLOB_OF[st]:
            out.append(f"table {st}: stage or blob wrong")
        if t.get("arm") != L.ARM_OF[st] or (t.get("arm") is not None and t.get("arm") not in ARMS):
            out.append(f"table {st}: arm line {t.get('arm')!r} is not the stage's allow-listed one")
        if int(t.get("stop_budget", 1)) != L.STOP_BUDGET[st]:
            out.append(f"table {st}: stop budget is not {L.STOP_BUDGET[st]}")
        if t.get("per_job_reset") != L.PER_JOB_RESET[st]:
            out.append(f"table {st}: per_job_reset is not the stage's")
        if FORBIDDEN_TABLE.search(json.dumps(t)):
            out.append(f"table {st}: a forbidden word (trc, kreg, kpoke, a clock-gate register, a BIF register, CLEAR2, xfer, kicker)")
        for j in t["jobs"]:
            n, row = j.get("name"), j.get("row")
            if row not in ROWS[st]:
                out.append(f"{st}/{n}: row {row} is not an approved row")
                continue
            if j.get("clear_values") != [0x8000, 0x40000] or j.get("hold_recovery") != ("Y" if j["skip"] else "N"):
                out.append(f"{st}/{n}: clear values or hold_recovery outside the allow-list")
            if j.get("timer_clock") not in L.CLOCKS:
                out.append(f"{st}/{n}: timer_clock {j.get('timer_clock')} is not one of {L.CLOCKS}")
        want = GEN.table(st)
        if json.loads(json.dumps(want)) != t:
            diff = [j["name"] for j, w in zip(t["jobs"], want["jobs"]) if j != w]
            out.append(f"table {st}: not the rows' table (r5layout.ROW_SPEC): differs in {diff or 'its header or its job list'}")
    return out


def run(root):
    root = pathlib.Path(root)
    out = []
    binfo = json.loads((root / "bins" / "blobs.json").read_text())
    regs = fw.load_regs()
    for name in BLOBS:
        text = (root / "asm" / f"{name}.s").read_text()
        blob = (root / "bins" / f"{name}.blob").read_bytes()
        out += check_blob(name, text, blob, regs)
        if binfo[name]["str"] or binfo[name].get("cont4") or binfo[name]["sa_writes"] or binfo[name].get("pa_writes"):
            out.append(f"{name}: blobs.json lists a str, a cont4, an sa write or a pa write")
    import hashlib
    if hashlib.sha256((root / "bins" / "ring_skip3p.blob").read_bytes()).hexdigest() != L.SKIP3P_SHA:
        out.append("ring_skip3p.blob is not R4-events' bytes (E836)")
    tabs = {st: json.loads((root / "tables" / f"{st}.json").read_text()) for st in ROWS}
    out += check_tables(tabs)
    return out


def main(argv):
    root = pathlib.Path(argv[argv.index("--root") + 1]) if "--root" in argv else R5
    problems = run(root)
    for p in problems:
        print("GUARD: " + p)
    if not problems:
        print(f"guard_blobs: clean ({len(BLOBS)} blobs, {len(ROWS)} tables)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
