def job(name, sset, **kw):
    j = {"name": name, "set": sset, "op": "ring", "window": 1, "trigger": "none", "open_ms": 20, "n": 0,
         "knobs": {}, "runid": 0}
    j.update(kw)
    return j


def reps(name, k, sset="control", **kw):
    return [job(name if i == 0 else f"{name}-r{i + 1}", sset if i == 0 else "replicate", **kw) for i in range(k)]


def hold_ms(n):
    return round(n * L.NS_PER_ITER[1] / 1e6 * 1.3 + 25)     # the window stays open past the hold's end


def stages():
    """S2b: E4 with every exit at mid-period (n = n_for_ticks(H): ((H + 0.5) * 25000 - 82) / 1.5, from run 3's 1.5 n
    + 15 and its start 64 to 70 units after the tick), then E5 at the 90-tick n.  No E1, no E2 (no sa write)."""
    st = {}
    n90 = L.n_for_ticks(90)
    st["e4c"] = {"blob": "ring_hold", "rows": "E4 row 1 (control: no hold, 16 ticks on the grid)", "gate": "e4c",
                 "jobs": reps("nohold", 3, "control", window=2, open_ms=20)}
    jobs = []
    for H in (1, 2, 3, 4, 6):
        n = L.n_for_ticks(H)
        jobs += reps(f"m{H}", 2, "heldout", window=2, n=n, open_ms=hold_ms(n), held_ticks=H)
    st["e4m"] = {"blob": "ring_hold", "rows": "E4 mid-phase holds of 1, 2, 3, 4 and 6 ticks", "gate": "e4m",
                 "jobs": jobs}
    st["e4l"] = {"blob": "ring_hold", "rows": "E4 a 90-tick mid-phase hold (about 90.5 ms), only if e4m passed",
                 "gate": "e4l", "jobs": reps("m90", 2, "heldout", window=2, n=n90, open_ms=hold_ms(n90), held_ticks=90)}
    st["e5c"] = {"blob": "ring_hold", "rows": "E5 rows 1-2 at the 90-tick n (only if e4l passed); kicks in window 2",
                 "gate": "e5c", "jobs":
                 reps("ctl90", 2, "control", window=2, n=n90, open_ms=hold_ms(n90), held_ticks=90) +
                 reps("kick90", 3, "heldout", window=2, n=n90, trigger="kick", open_ms=hold_ms(n90), held_ticks=90)}
    st["e5t"] = {"blob": "ring_hold", "rows": "E5 rows 4 then 3 at the 90-tick n (only if e5c passed)", "gate": None,
                 "jobs": reps("tri-nohold", 2, "control", window=1, trigger="tool:tri64") +
                 reps("tri90", 3, "heldout", window=1, n=n90, trigger="tool:tri64", open_ms=hold_ms(n90),
                      knobs={"hold_recovery": "Y"}, stuck_ends_stage=True, held_ticks=90)}
    runid = 0x5200
    for name, s in st.items():
        s["stage"] = name
        s["arm"] = ARM[s["blob"]]
        for j in s["jobs"]:
            runid += 1
            j["runid"] = runid
            if j.get("trigger", "").startswith("tool:"):
                j["tool_args"] = TOOL_ARGS[j["trigger"][5:]]
                j["tool_timeout_s"] = 30
            assert 0 <= j.get("n", 0) <= L.N_MAX
    return st


