def hold_units(n):
    lo, hi = L.iter_ms(n)
    return int(lo * 0.7 * L.TIMER_HZ / 1000), int(hi * 1.5 * L.TIMER_HZ / 1000)


def baseline_order():
    """predictions/e1-baseline-order.tsv: the first-rise orders of CR_EVENT_STATUS per kind (E547's timelines,
    resgx545-data platform/event-bits/analysis/events-timelines.txt), the offline baseline of Q111's order clause."""
    src = pathlib.Path.home() / "src/resgx545-data/platform/event-bits/analysis/events-timelines.txt"
    rows = ["kind\trun\tcount\torder"]
    kind, reg = None, None
    for ln in src.read_text().splitlines():
        m = re.match(r"== (\S+) (r\d+):", ln)
        if m:
            kind = f"{m.group(1)}\t{m.group(2)}"
            continue
        m = re.match(r"\s+(0x[0-9a-f]+): pulses", ln)
        if m:
            reg = m.group(1)
            continue
        m = re.match(r"\s+first-rise order x(\d+):(.*)$", ln)
        if m and reg == "0x012c" and m.group(2).strip():
            rows.append(f"{kind}\t{m.group(1)}\t{m.group(2).strip()}")
    return "\n".join(rows) + "\n"


def tables_md(st, info):
    out = ["# S2b job tables (generated by gen/gen_s2.py; the JSON in tables/ is what runs)", "",
           "n for H held ticks = ((H + 0.5) * 25000 - 82) / 1.5, rounded (exit mid-period; S2 run 3: hold = 1.5 n + 15 "
           "units, start 64 to 70 units after the tick): " +
           ", ".join(f"H {H}: n {L.n_for_ticks(H)}" for H in (1, 2, 3, 4, 6, 90)), ""]
    out += ["| blob | insns | bytes | sha256 | arm | sa writes | str |", "|---|---|---|---|---|---|---|"]
    for k, v in info.items():
        out.append(f"| {k} | {v['insns']} | {v['bytes']} | {v['sha256'][:16]}... | `{v['arm']}` | "
                   f"{', '.join(v['sa_writes']) or 'none'} | {v['str']} |")
    for name in ORDER:
        s = st[name]
        out += ["", f"## {name}: {s['rows']} (blob {s['blob']}, gate after: {s['gate'] or 'none (stage rc only)'})",
                "", "| job | set | op | window | trigger | n | open ms | knobs | runid |", "|---|---|---|---|---|---|---|---|---|"]
        for j in s["jobs"]:
            trig = j.get("trigger", f"cmd {j.get('cmd')}" + (f" M={j['mark']:#x}" if isinstance(j.get("mark"), int)
                                                              else f" M={j.get('mark', '')}"))
            out.append(f"| {j['name']} | {j['set']} | {j['op']} | {j.get('window', '-')} | {trig} | {j.get('n', '-')} | "
                       f"{j.get('open_ms', j.get('wait_ms', '-'))} | {j.get('knobs') or ''} | {j['runid']:#x} |")
    return "\n".join(out) + "\n"


