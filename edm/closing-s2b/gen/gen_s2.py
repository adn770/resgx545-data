def h1_bits(status):      # E155: pa1 bit = 22 - status bit (bits above 22 have no place); + bit 8, the host kick
    return sorted({22 - b for b in status if b <= 22} | {8})


def h2_bits(status):      # E146: the same position, inside pa1[23:0] (31:24 is the count, S2 run 1); + bit 8
    return sorted({b for b in status if b <= 23} | {8})


def held_rows(j, set_label):
    """The frozen rows of one hold job of S2b (fit: S2 run 3 where it says so; held out for this run)."""
    n, H, nm = j["n"], j["held_ticks"], j["name"]
    hu = L.hold_units_of(n)
    band = (int(hu * 0.998 - 50), int(hu * 1.002 + 50))
    q = min(H, L.QUEUE_CAP)
    sig = min(H, 3)
    return [(nm, "hold_units", "%d..%d" % band, "knob (fit: S2 run 3, 1.5 n + 15 within 2)", "control"),
            (nm, "held", str(H), "design (exit mid-period: ((H + 0.5) * 25000 - 82) / 1.5)", "control"),
            (nm, "q", str(q), "cap min(H, 4) (fit: S2 run 3, 10 of 10 holds of 6, 18, 90 ticks)", set_label),
            (nm, "q_alt", "0", "LOST", "alternative"), (nm, "q_alt", "1", "ONE", "alternative"),
            (nm, "q_alt", str(H), "ALL", "alternative"),
            (nm, "pa2_signature", f"the first {sig} entries after the exit 0x01061a74" +
             ("; the 4th an EVENT_TIMER sample, (400000 - pa2[23:0]) / 16 = first entry - last held grid tick within 25"
              if H >= 4 else ""), "fit: S2 run 3 (12 clocks after a reload: queued, latched on arrival)", set_label),
            (nm, "window_count", "slot-0 logged + drops = open_ms * 0.99746 - H + min(H, 4) within 1.5",
             "second instrument (fit: S2 run 3: 26, 32, 38, 74 within 0.5)", set_label)]


