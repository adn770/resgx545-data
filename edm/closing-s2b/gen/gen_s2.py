HDR = """; SPDX-License-Identifier: MIT
; {name} -- generated by closing/s2/gen/gen_s2.py (S2 of the question-closing pass, PREPARED, NOT RUN): {what}
; Our own source, written from doc/specs/usse_isa.md, asm/fwtask/events_m.s, slow.s, state2.s and the records
; E146, E155, E532, E536, E538, E539; run as an EDM task from the page the kernel maps (index 0x4000); only forms
; the landed verifier accepts.  Registers r1-r18 and r22-r31 only (the ones earlier tasks of ours wrote).
; No str, no emit, no lock, no clock-gate register; every store the same value from every lane.
"""
TRIPLE = """t{k}:
        mov r30, #0xdeadbeef                ; @patch cont{k}
        mov pclink, r30
        lapc
"""


def ring_entry(k, hold):
    """The entry of slot k: capture, (hold: pass counter and busy flag), window test and filter, the ladder."""
    base = L.RING_BASE[k] * 4
    a = [f"@entry {k}",
         "        mov r1, #0xdeadbeef                 ; @patch res+0",
         f"        mov r2, #0xdeadbeef                 ; @patch res+{base:#x}",
         "        mov r4, pa0",
         "        mov r5, pa1",
         "        mov r6, pa2",
         "        ldr r11, #81, drc0                  ; CR_TIMER at the pass's start",
         "        wdf drc0"]
    if hold:
        a += [f"        ldad.bypassl1 r8, [r1,+#{L.PASS + k}], drc0",
              f"        ldad.bypassl1 r12, [r1,+#{L.STATE}], drc0",
              "        wdf drc0",
              "        mov r9, #0xffffffff",
              "        ima32.u r8, r8, #1, r9.neg",
              f"        stad [r1,+#{L.PASS + k}], r8                  ; passes of slot {k}",
              "        idf drc0, bif",
              "        wdf drc0",
              "        xor.testtanz.chan0 !c0, p2, r12, #1  ; p2 = state is not busy",
              f"        p2 br @w{k}",
              "        mov r7, #0x00000001",
              f"        stad [r1,+#{L.OVL + k}], r7                  ; a pass found the state busy",
              f"        stad [r1,+#{L.OVL_LOG + 4 * k}], r4",
              f"        stad [r1,+#{L.OVL_LOG + 4 * k + 1}], r5",
              f"        stad [r1,+#{L.OVL_LOG + 4 * k + 2}], r6",
              f"        stad [r1,+#{L.OVL_LOG + 4 * k + 3}], r11",
              "        idf drc0, bif",
              "        wdf drc0",
              f"w{k}:"]
    a += [f"        ldad.bypassl1 r3, [r1,+#{L.WINDOW}], drc0   ; the window",
          "        wdf drc0",
          "        and.testtanz.chan0 !c0, p0, r3, r3  ; p0 = window open",
          f"        !p0 br @x{k}",
          "        xor.testtaz.chan0 !c0, p1, r3, #2   ; p1 = window 2: every pass",
          f"        p1 br @s{k}_0",
          "        mov r9, #0x00ffffff",
          "        and.testtanz.chan0 !c0, p1, r5, r9  ; p1 = pa1[23:0] not 0 (31:24 is a count, S2 run 1)",
          f"        p1 br @s{k}_0",
          "        xor.testtanz.chan0 !c0, p1, r4, #2  ; p1 = pa0 is not 2",
          f"        p1 br @s{k}_0",
          f"        br @x{k}                             ; a plain tick in window 1: not logged"]
    n = L.RUNGS[k]
    for j in range(n):
        o = L.RUNG * j
        nxt = f"s{k}_{j + 1}" if j + 1 < n else f"full{k}"
        a += [f"s{k}_{j}:",
              f"        ldad.bypassl1 r7, [r2,+#{o}], drc0",
              "        wdf drc0",
              "        and.testtanz.chan0 !c0, p0, r7, r7  ; p0 = rung taken",
              f"        p0 br @{nxt}",
              "        mov r7, #0x00000001",
              f"        stad [r2,+#{o}], r7",
              f"        stad [r2,+#{o + 1}], r4",
              f"        stad [r2,+#{o + 2}], r5",
              f"        stad [r2,+#{o + 3}], r6",
              f"        stad [r2,+#{o + 4}], r11",
              "        idf drc0, bif",
              "        wdf drc0",
              f"        br @x{k}"]
    a += [f"full{k}:",
          f"        ldad.bypassl1 r8, [r1,+#{L.DROP + k}], drc0",
          "        wdf drc0",
          "        mov r9, #0xffffffff",
          "        ima32.u r8, r8, #1, r9.neg",
          f"        stad [r1,+#{L.DROP + k}], r8                 ; the ring is full: counted, not lost silently",
          "        idf drc0, bif",
          "        wdf drc0",
          f"        br @x{k}"]
    if hold and k == 0:
        a += ["x0:",
              f"        ldad.bypassl1 r13, [r1,+#{L.CMD}], drc0",
              "        wdf drc0",
              "        xor.testtaz.chan0 !c0, p1, r13, #1  ; p1 = cmd 1: hold",
              "        p1 br @h0",
              "        br @t0",
              "h0:",
              f"        ldad.bypassl1 r8, [r1,+#{L.N_ITER}], drc0   ; n",
              "        wdf drc0",
              "        mov r14, #0x00000001",
              f"        stad [r1,+#{L.STATE}], r14                  ; state = busy",
              "        ldr r15, #81, drc0",
              "        wdf drc0",
              f"        stad [r1,+#{L.HOLD_ENTRY}], r15                 ; CR_TIMER at the hold's start",
              "        idf drc0, bif",
              "        wdf drc0",
              "        and.testtanz.chan0 !c0, p1, r8, r8  ; n = 0: no loop at all",
              "        !p1 br @e0",
              "        mov r9, #0x00000001",
              "loop0:",
              "        ima32.u r8, r8, #1, r9.neg",
              "        xor.testtanz.chan0 !c0, p1, r8, #0",
              "        p1 br @loop0",
              "e0:",
              "        ldr r15, #81, drc0",
              "        wdf drc0",
              f"        stad [r1,+#{L.HOLD_EXIT}], r15                 ; CR_TIMER at the hold's end",
              f"        ldad.bypassl1 r16, [r1,+#{L.RUNID}], drc0",
              "        wdf drc0",
              f"        stad [r1,+#{L.ECHO}], r16                  ; the run id, echoed",
              "        mov r14, #0x00000000",
              f"        stad [r1,+#{L.CMD}], r14                  ; cmd = 0",
              "        idf drc0, bif",
              "        wdf drc0",
              "        mov r14, #0x00000002",
              f"        stad [r1,+#{L.STATE}], r14                  ; state = done",
              "        idf drc0, bif",
              "        wdf drc0",
              "        br @t0"]
    else:
        a += [f"x{k}:"]
    return "\n".join(a) + "\n" + TRIPLE.format(k=k)


def ring_source(hold):
    name = "ring_hold.s" if hold else "ring_e1.s"
    what = ("E4/E5: the ring of ring_e1.s plus pass counters, busy flags and the slow loop of slot 0 (cmd 1) "
            "stamped with CR_TIMER at its start and end" if hold else
            "E1: the event ring; window 0 tail-calls at once, 1 logs all but plain ticks, 2 logs every pass")
    return HDR.format(name=name, what=what) + "\n" + "".join(ring_entry(k, hold) for k in range(4))


def area_stores(base):
    regs = ["r4", "r5", "r6", "r7", "r8", "r10", "r11", "r12", "r13", "r14", "r15", "r16"]
    return [f"        stad [r1,+#{base + i}], {r}                  ; {f}" for i, (r, f) in
            enumerate(zip(regs, L.AREA_FIELDS))]


def pa_source(write):
    name = "pa_write.s" if write else "pa_read.s"
    what = ("E2a writes: cmd 1 reads, cmd 2 writes sa67 = M, cmd 3 writes sa68 = M, each read back in the same "
            "pass; cmd 9 (the next pass) reads again; p0..p3 at the tail of a write from the page flags"
            if write else "E2a read pass: cmd 1 stores pa0..pa4, sa64..sa68, sa0 and CR_TIMER; cmd 9, armed by "
            "cmd 1 for the next pass, stores them again; no sa write")
    a = ["@entry 0",
         "        mov r1, #0xdeadbeef                 ; @patch res+0",
         "        mov r4, pa0", "        mov r5, pa1", "        mov r6, pa2", "        mov r7, pa3",
         "        mov r8, pa4",
         "        mov r10, sa64", "        mov r11, sa65", "        mov r12, sa66", "        mov r13, sa67",
         "        mov r14, sa68", "        mov r15, sa0",
         "        ldr r16, #81, drc0",
         "        wdf drc0",
         f"        ldad.bypassl1 r2, [r1,+#{L.CMD}], drc0",
         "        wdf drc0",
         "        and.testtanz.chan0 !c0, p0, r2, r2",
         "        p0 br @work",
         "tail:",
         "        mov r30, #0xdeadbeef                ; @patch cont0",
         "        mov pclink, r30",
         "        lapc",
         "work:",
         "        xor.testtaz.chan0 !c0, p1, r2, #1",
         "        p1 br @c1",
         "        xor.testtaz.chan0 !c0, p1, r2, #9",
         "        p1 br @c9"]
    if write:
        a += ["        xor.testtaz.chan0 !c0, p1, r2, #2",
              "        p1 br @c2",
              "        xor.testtaz.chan0 !c0, p1, r2, #3",
              "        p1 br @c3"]
    a += ["        br @tail",
          "c1:"] + area_stores(L.AREA_A) + [
          f"        ldad.bypassl1 r9, [r1,+#{L.RUNID}], drc0",
          "        wdf drc0",
          f"        stad [r1,+#{L.ECHO}], r9",
          "        mov r3, #0x00000009",
          f"        stad [r1,+#{L.CMD}], r3                   ; cmd = 9: the next pass reads again",
          "        idf drc0, bif",
          "        wdf drc0",
          "        mov r3, #0x00000002",
          f"        stad [r1,+#{L.STATE}], r3                   ; state = done",
          "        idf drc0, bif",
          "        wdf drc0",
          "        br @tail",
          "c9:"] + area_stores(L.AREA_B) + [
          "        mov r3, #0x00000000",
          f"        stad [r1,+#{L.CMD}], r3                   ; cmd = 0",
          "        idf drc0, bif",
          "        wdf drc0",
          "        mov r3, #0x00000003",
          f"        stad [r1,+#{L.STATE}], r3                   ; state = next pass read",
          "        idf drc0, bif",
          "        wdf drc0",
          "        br @tail"]
    if write:
        for cmd, sa, pa, c in ((2, "sa67", "pa3", L.AREA_C), (3, "sa68", "pa4", L.AREA_C + 2)):
            a += [f"c{cmd}:"] + area_stores(L.AREA_A) + [
                  f"        ldad.bypassl1 r9, [r1,+#{L.MARK}], drc0   ; M",
                  "        wdf drc0",
                  f"        mov {sa}, r9                       ; the one write of this command",
                  f"        mov r17, {pa}",
                  f"        mov r18, {sa}",
                  f"        stad [r1,+#{c}], r17                  ; {pa} after the write, same pass",
                  f"        stad [r1,+#{c + 1}], r18                  ; {sa} after the write, same pass",
                  "        br @fin"]
        a += ["fin:",
              f"        ldad.bypassl1 r22, [r1,+#{L.PFLAGS}], drc0",
              f"        ldad.bypassl1 r23, [r1,+#{L.PFLAGS + 1}], drc0",
              f"        ldad.bypassl1 r24, [r1,+#{L.PFLAGS + 2}], drc0",
              f"        ldad.bypassl1 r25, [r1,+#{L.PFLAGS + 3}], drc0",
              f"        ldad.bypassl1 r9, [r1,+#{L.RUNID}], drc0",
              "        wdf drc0",
              f"        stad [r1,+#{L.ECHO}], r9",
              "        mov r3, #0x00000009",
              f"        stad [r1,+#{L.CMD}], r3                   ; cmd = 9: the next pass reads again",
              "        idf drc0, bif",
              "        wdf drc0",
              "        mov r3, #0x00000002",
              f"        stad [r1,+#{L.STATE}], r3                   ; state = done",
              "        idf drc0, bif",
              "        wdf drc0",
              "        and.testtanz.chan0 !c0, p0, r22, r22   ; p0..p3 at the tail call as E536's writer",
              "        and.testtanz.chan0 !c0, p1, r23, r23",
              "        and.testtanz.chan0 !c0, p2, r24, r24",
              "        and.testtanz.chan0 !c0, p3, r25, r25",
              "        br @tail"]
    return HDR.format(name=name, what=what) + "\n" + "\n".join(a) + "\n"


ARM = {"ring_hold": "slots=0xf entry=0,1,2,3"}


def build_blobs():
    """S2b builds ring_hold only (the S2 run-2 source, the count-byte filter): no sa write exists in any S2b blob."""
    regs = fwtask.load_regs()
    info = {}
    for nm, text in (("ring_hold", ring_source(True)),):
        (S2 / "asm" / f"{nm}.s").write_text(text)
        blob = fwtask.build_blob_text(text, regs)            # raises VerifyError if the verifier refuses
        (S2 / "bins" / f"{nm}.blob").write_bytes(blob)
        p = fwtask.parse_blob(blob)
        src = text.splitlines()
        info[nm] = {"insns": len(p.words), "bytes": len(blob), "patches": len(p.patches), "entries": p.entries,
                    "sha256": hashlib.sha256(blob).hexdigest(), "arm": ARM[nm],
                    "sa_writes": sorted({m.group(1) for ln in src for m in [re.match(r"\s+mov (sa\d+),", ln)] if m}),
                    "str": sum(1 for ln in src if re.match(r"\s+str ", ln))}
    (S2 / "bins" / "blobs.json").write_text(json.dumps(info, indent=1, sort_keys=True) + "\n")
    return info


