"""guard_blobs.py [--root DIR]: the laptop limits applied to the ASSEMBLED code of every blob and to every table of R3k.
Exit 0 clean, 1 with one `GUARD:` line a finding.  Run by run/guard_r3.sh; the tests feed it bad blobs and bad tables.

What it checks (the limits of the kernel batch, R3-K1 to R3-K11):
  * each bins/NAME.blob is exactly what asm/NAME.s assembles to (the landed `fwtask.build_blob_text`, which runs the landed verifier), and the
    source's instructions are the blob's words, one for one;
  * `str` words decoded from the WORD: only the register indices of r3layout.STR_OF (#691 in ring_timer, #69 in strclr, #77 in ring_skip3), each
    in the block that names it; ring_timer's two #691 stores take r12, set by a `mov r12, #0x01061a80` (r3layout.TIMER_STR_WORD, the word the
    closed tick handler stores, E155) on the line before, and nothing else writes r12 there; `ldr` only of register #81 (CR_TIMER);
  * `mov` to a pa register (the verifier row MOVPA) only in pa_write2.s: pa3 in command 4, pa4 in 5, pa2 in 6, never pa0, pa1; the sa
    registers a command may write are exactly r3layout.CMD_SA2 (alias2.s) or r3layout.PW_SA (pa_write2.s: sa67 in command 2, sa68 in 3), no
    other blob writes any sa; r20, r21, i0, i1 only in alias2.s commands 6 and 11; pclink only by the patched continue triples;
  * the exit's own words (cfi.global, phas ... end) only in ring_exit.s's blocks endc / endp / endb, exactly as the exit orders them; the
    `@patch cont4` triple exactly once, in ring_exit.s's block act4, and nowhere else;
  * the tables are exactly the rows of r3layout.ROW_SPEC (regenerated by gen/gen_r3.py and compared); the only trigger is `none` or `miscinfo`
    (the kernel's own command and kick: never a bare kick); arm lines from the allow-list; no trc, no kpoke, no clock register in a table; the
    values ever written to the clear registers are r3layout.CLEAR2_BITS (CLEAR2, bits 15 and 6) and CLEAR_BITS (CLEAR, bits 15 and 18) and,
    after a stop only, bit 29; the kicker word is 0x42.
"""
import json
import os
import pathlib
import re
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
R3 = HERE.parent
sys.path.insert(0, str(R3 / "gen"))
import r3layout as L  # noqa: E402
import r3blobs as B  # noqa: E402
import gen_r3 as GEN  # noqa: E402

fw = B.fwtask
TEMP_MASK = (0x1FF << 21) | (1 << 51)
ARMS = {a for a in L.ARM_OF.values() if a}
ROWS = {st: set(rows) for st, rows in L.ROW_SPEC.items()}
BLOB_OF = L.BLOB_OF
BLOBS = L.BLOBS
SPECIAL_CMDS = {6, 11}
EXIT_WORDS = (0xF843B300A0000180, 0xFA44070000000000)


def _ref():
    """{destination bits of a mov reg word: (bank, index)} from reference assemblies of `mov rN, r11` and `mov saN, r11`."""
    ref = {}
    for bank, base in (("r", 0), ("sa", 0), ("i", 124)):
        for n in range(128 if bank != "i" else 4):
            try:
                w = fw.assemble_text(f"mov {bank}{n}, r11")[0]
            except Exception:
                continue
            ref.setdefault(w & TEMP_MASK, ("r" if bank == "i" else bank, n + base))
    return ref


REF = _ref()


def dest_of(w):
    """('sa', n), ('i', n), ('r20',), ('r21',), ('temp', n) or ('unknown',) of a MOVREG word."""
    d = REF.get(w & TEMP_MASK)
    if d is None:
        return ("unknown",)
    bank, n = d
    if bank == "sa":
        return ("sa", n)
    if n in (20, 21):
        return (f"r{n}",)
    if n >= 124:
        return ("i", n - 124)
    return ("temp", n)


def label_ranges(text):
    """{label: (first instruction index, last + 1)} of a source (a label runs to the next label)."""
    idx, cur, out, last = 0, None, {}, None
    for _, lab, s in B.code_lines(text):
        if lab:
            if cur is not None:
                out[cur] = (out[cur][0], idx)
            cur = lab
            out[cur] = (idx, idx)
        elif not s.startswith("@"):
            idx += 1
    if cur is not None:
        out[cur] = (out[cur][0], idx)
    return out


def blocks_of(text):
    """{label: (first index, last + 1)} (a label runs to the next label)."""
    return label_ranges(text)


def in_block(i, rng, names):
    return any(n in rng and rng[n][0] <= i < rng[n][1] for n in names)


def scan(name, text, blob, regs=None):
    """The findings about one assembled blob as a dict."""
    regs = regs or fw.load_regs()
    p = fw.parse_blob(blob)
    words = p.words
    lines = B.instructions(text)
    rng = blocks_of(text)
    f = {"problems": [], "str": [], "ldr": set(), "sa_by_cmd": {}, "sa_all": set(), "special_writes": {}, "pclink": 0, "pa": {}, "exit": {}}
    if len(lines) != len(words):
        f["problems"].append(f"source has {len(lines)} instructions, the blob {len(words)} words")
        return f
    cmd_of = {}
    for lab, (a, b) in rng.items():
        m = re.fullmatch(r"c(\d+)([a-z]\w*)?", lab)
        if m:
            for i in range(a, b):
                cmd_of[i] = int(m.group(1))
    for i, w in enumerate(words):
        kind, nm = fw.classify(w)
        if kind == "STR":
            idx = fw.reg_index(w)
            f["str"].append(idx)
            if idx not in L.STR_OF.get(name, []):
                f["problems"].append(f"word {i}: str of register #{idx} ({lines[i]}); {name} may carry {L.STR_OF.get(name, [])}")
            elif name == "ring_timer":
                prev = lines[i - 1] if i else ""
                if prev.split(";")[0].split() != ["mov", "r12,", f"#0x{L.TIMER_STR_WORD:08x}"] or not lines[i].startswith("str #691, r12"):
                    f["problems"].append(f"word {i}: the EVENT_TIMER store is not `mov r12, #{L.TIMER_STR_WORD:#010x}` then `str #691, r12`")
                if not in_block(i, rng, ("tstr", "tstre")):
                    f["problems"].append(f"word {i}: the EVENT_TIMER store is outside tstr / tstre")
            elif name == "ring_skip3" and not lines[i].startswith("str #77, r10"):
                f["problems"].append(f"word {i}: the CLEAR store is not `str #77, r10` ({lines[i]})")
            elif name == "strclr" and not (lines[i].startswith("str #69, r10") and in_block(i, rng, ("c1",))):
                f["problems"].append(f"word {i}: the CLEAR2 store is not `str #69, r10` in c1 ({lines[i]})")
        elif kind == "LDR":
            idx = fw.reg_index(w)
            f["ldr"].add(idx)
            if idx != 81:
                f["problems"].append(f"word {i}: ldr of register #{idx} ({lines[i]}); only #81 (CR_TIMER) is allowed")
        elif kind == "MOVPCLINK":
            f["pclink"] += 1
        elif kind == "MOVPA":
            n = fw.dst_num(w)
            f["pa"].setdefault(cmd_of.get(i), set()).add(f"pa{n}")
            if name != "pa_write2":
                f["problems"].append(f"word {i}: a mov to a pa register outside pa_write2.s ({lines[i]})")
            elif f"pa{n}" not in lines[i].split(",")[0]:
                f["problems"].append(f"word {i}: a pa{n} write the source line does not show ({lines[i]})")
        elif kind == "MOVREG":
            d = dest_of(w)
            src_dest = B.writes_of([lines[i]])
            if d[0] == "sa":
                f["sa_all"].add(f"sa{d[1]}")
                f["sa_by_cmd"].setdefault(cmd_of.get(i), set()).add(f"sa{d[1]}")
                if src_dest != [f"sa{d[1]}"]:
                    f["problems"].append(f"word {i}: an sa{d[1]} write the source line does not show ({lines[i]})")
            elif d[0] in ("r20", "r21", "i"):
                nm2 = d[0] if d[0] != "i" else f"i{d[1]}"
                f["special_writes"].setdefault(cmd_of.get(i), set()).add(nm2)
            elif d[0] == "unknown":
                f["problems"].append(f"word {i}: a register move to a bank the guard cannot decode ({lines[i]})")
        if w in EXIT_WORDS:
            f["exit"].setdefault(w, []).append(i)
    return f


def check_blob(name, text, blob, policy, regs=None):
    """Problems of one blob against its policy (see policy_of)."""
    regs = regs or fw.load_regs()
    out = []
    try:
        if fw.build_blob_text(text, regs) != blob:
            out.append(f"{name}: the blob is not what its source assembles to")
    except fw.VerifyError as e:
        out.append(f"{name}: the landed verifier refuses the source: {e}")
    try:
        bad = fw.verify_blob(blob, regs)
    except Exception as e:
        bad = [repr(e)]
    if bad:
        out.append(f"{name}: the landed verifier refuses the blob: {bad[:2]}")
    try:
        f = scan(name, text, blob, regs)
    except Exception as e:
        return out + [f"{name}: the scan failed: {e!r}"]
    out += [f"{name}: {x}" for x in f["problems"]]
    if sorted(f["str"]) != sorted(L.STR_OF.get(name, [])):
        out.append(f"{name}: str registers {sorted(f['str'])}, not {sorted(L.STR_OF.get(name, []))}")
    if policy["cmd_sa"] is None:
        if f["sa_all"]:
            out.append(f"{name}: writes {sorted(f['sa_all'])}; this blob may write no sa register")
    else:
        if not f["sa_all"] <= policy["sa_allowed"]:
            out.append(f"{name}: writes {sorted(f['sa_all'] - policy['sa_allowed'])}; only {sorted(policy['sa_allowed'])} are allowed")
        got = {c: sorted(s) for c, s in f["sa_by_cmd"].items() if c is not None}
        want = {c: sorted(s) for c, s in policy["cmd_sa"].items() if s}
        if got != want:
            out.append(f"{name}: sa writes by command are {got}, not {want}")
        if None in f["sa_by_cmd"]:
            out.append(f"{name}: an sa write outside any command block")
    want_pa = {c: sorted(v) for c, v in policy.get("pa", {}).items() if v}
    got_pa = {c: sorted(s) for c, s in f["pa"].items()}
    if got_pa != want_pa:
        out.append(f"{name}: pa writes by command are {got_pa}, not {want_pa}")
    for c, s in f["special_writes"].items():
        if c is None or c not in policy["special_ok_cmds"]:
            out.append(f"{name}: writes {sorted(s)} in {'command ' + str(c) if c is not None else 'the common code'}; only commands "
                       f"{sorted(policy['special_ok_cmds'])} may")
    pb = fw.parse_blob(blob)
    ent = len(pb.entries)
    if f["pclink"] != ent + policy["extra_triples"]:
        out.append(f"{name}: {f['pclink']} pclink writes for {ent} entries (only the continue triples: once an entry"
                   + (f" and {policy['extra_triples']} more" if policy["extra_triples"] else "") + ")")
    out += cont_problems(name, text, pb, policy)
    rng = blocks_of(text)
    exits = {hex(w): idx for w, idx in f["exit"].items()}
    if name == "ring_exit":
        # the exit's words only in endc (cfi), endp (phas), endb (both); each block's instructions exactly as the exit orders them
        want = {"endc": [0xF843B300A0000180], "endp": [0xFA44070000000000], "endb": [0xF843B300A0000180, 0xFA44070000000000]}
        for lab, ws in want.items():
            a, b = rng.get(lab, (0, 0))
            got = [words_i for words_i in (pb.words[k] for k in range(a, b)) if words_i in EXIT_WORDS]
            if got != ws:
                out.append(f"{name}: block {lab} has the exit words {[hex(x) for x in got]}, not {[hex(x) for x in ws]}")
            if not (a < b and fw.classify(pb.words[b - 1])[0] == "NOP"):
                out.append(f"{name}: block {lab} does not end in nop.end")
        total = sum(len(v) for v in f["exit"].values())
        if total != 4:
            out.append(f"{name}: {total} exit words in the code (4: cfi in endc and endb, phas in endp and endb)")
    elif f["exit"]:
        out.append(f"{name}: carries the closed exit's words {exits} (only ring_exit.s may)")
    return out


def cont_problems(name, text, pb, policy):
    """The continue patches: one `contK` a tail triple, K the entry's slot; ring_exit.s has one more, `cont4` inside the block act4."""
    out = []
    conts = [(p.index, p.kind) for p in pb.patches if p.kind.startswith("cont")]
    want_kinds = sorted(f"cont{k}" for k in range(len(pb.entries))) if len(pb.entries) > 1 else ["cont0"]
    rng = label_ranges(text)
    if policy["extra_triples"]:
        want_kinds = sorted(want_kinds + ["cont4"])
        a, b = rng.get("act4", (0, 0))
        inside = [i for i, k in conts if a <= i < b]
        if len(inside) != 1 or dict(conts)[inside[0]] != "cont4":
            out.append(f"{name}: the cont4 patch is not exactly one `cont4` inside the act4 block")
    if sorted(k for _, k in conts) != want_kinds:
        out.append(f"{name}: continue patches {sorted(k for _, k in conts)}, not {want_kinds}")
    return out


def policy_of(name):
    base = {"cmd_sa": None, "sa_allowed": set(), "special_ok_cmds": set(), "extra_triples": 0, "pa": {}}
    if name == "alias2":
        base.update({"cmd_sa": {c: set(v) for c, v in L.CMD_SA2.items()}, "sa_allowed": set(L.SA_ALLOWED2), "special_ok_cmds": SPECIAL_CMDS})
    elif name == "pa_write2":
        base.update({"cmd_sa": {c: set(v) for c, v in L.PW_SA.items()}, "sa_allowed": {"sa67", "sa68"},
                     "pa": {c: set(v) for c, v in L.PW_PA.items()}})
    elif name == "ring_exit":
        base["extra_triples"] = 1
    return base


FORBIDDEN_TABLE = re.compile(r"\btrc\b|trc_hazard|kreg(?!now)|kpoke|alias_skip|clk|CLK|knob|xfer|bare|0x0c00|0x0c04")
TRIGGERS = {"none", "miscinfo"}


def check_rowspec():
    """The frozen values of r3layout.ROW_SPEC itself: what may ever be written to a register or a kicker."""
    out = []
    if set(L.CLEAR2_BITS) != {0x8000, 0x40}:
        out.append(f"r3layout.CLEAR2_BITS {L.CLEAR2_BITS} is not bits 15 and 6")
    if set(L.CLEAR_BITS) != {0x8000, 0x40000} or L.CLEAR_TIMER_BIT != 0x20000000:
        out.append("r3layout.CLEAR_BITS / CLEAR_TIMER_BIT are not bits 15, 18 / 29")
    if L.KICKER_WORD != 0x42 or L.TIMER_STR_WORD != 0x01000000 | L.EVT_RELOAD:
        out.append("the kicker word or the EVENT_TIMER word is not the frozen one")
    for st, rows in L.ROW_SPEC.items():
        for row, spec in rows.items():
            if spec["op"] not in L.STAGE_INFO[st]["ops"]:
                out.append(f"{st}/{row}: op {spec['op']} is not allowed in this stage")
            if spec["op"] == "pawrite" and spec["cmd"] not in L.PW_PA:
                out.append(f"{st}/{row}: pawrite command {spec['cmd']} unknown")
            if spec["op"] == "act" and spec["act"] and spec["act"] not in L.ACT_OF_STAGE[st]:
                out.append(f"{st}/{row}: act {spec['act']} is not one of the stage's {L.ACT_OF_STAGE[st]}")
            if spec["op"] == "kicker" and spec["set_kicker"] not in (None, 0x42):
                out.append(f"{st}/{row}: kicker word {spec['set_kicker']}")
            if spec["op"] == "skip3" and spec["skip"] not in (0, 1):
                out.append(f"{st}/{row}: skip flag {spec['skip']}")
    for m in L.PW_MARK.values():
        if not m:
            out.append("a zero e2b marker")
    return out


def check_tables(tables, binfo):
    """Problems of the job tables ({stage: table}) against r3layout.ROW_SPEC (the tables regenerated from it are compared whole)."""
    out = check_rowspec()
    for st, t in tables.items():
        if t.get("stage") != st or t.get("blob") != BLOB_OF[st]:
            out.append(f"table {st}: stage or blob wrong")
        if t.get("arm") != L.ARM_OF[st] or (t.get("arm") is not None and t.get("arm") not in ARMS):
            out.append(f"table {st}: arm line {t.get('arm')!r} is not the stage's allow-listed one")
        if int(t.get("stop_budget", 1)) != L.STOP_BUDGET[st]:
            out.append(f"table {st}: stop budget is not {L.STOP_BUDGET[st]}")
        if t.get("per_job_reset") != L.PER_JOB_RESET[st]:
            out.append(f"table {st}: per_job_reset is not the stage's")
        text = json.dumps(t)
        if FORBIDDEN_TABLE.search(text):
            out.append(f"table {st}: a forbidden word (trc, kreg, kpoke, a knob, a clock register, a BIF register, xfer)")
        for j in t["jobs"]:
            n, row = j.get("name"), j.get("row")
            if row not in ROWS[st]:
                out.append(f"{st}/{n}: row {row} is not an approved row")
                continue
            if j.get("trigger", "none") not in TRIGGERS:
                out.append(f"{st}/{n}: trigger {j.get('trigger')!r} is not none or miscinfo (never a bare kick)")
            if j["op"] == "alias2":
                blob_sa = sorted(binfo["alias2"]["cmd_sa"].get(str(j["cmd"]), []))
                if sorted(j["sa"]) != blob_sa or not set(j["sa"]) <= L.SA_ALLOWED2:
                    out.append(f"{st}/{n}: sa set {j['sa']} is not what the blob's command {j['cmd']} writes ({blob_sa})")
                w = j.get("w65")
                if w and "or" in w and row in ("C1", "C3") and w["or"] & L.TESTED_PA1_MASK:
                    out.append(f"{st}/{n}: the word carries a bit some ukernel code tests ({w['or']:#x})")
            if j["op"] == "holdsig" and (j["n"] not in (0, L.n_for_ticks(L.K7_HOLD_TICKS)) or j["window"] != 2):
                out.append(f"{st}/{n}: hold n or window outside the allow-list")
            if j["op"] == "pawrite" and (any(p in ("pa0", "pa1") for p in j["pa"]) or j["cmd"] not in L.PW_PA):
                out.append(f"{st}/{n}: a pa write outside pa2-pa4")
        want = GEN.table(st)
        if json.loads(json.dumps(want)) != t:
            diff = [j["name"] for j, w in zip(t["jobs"], want["jobs"]) if j != w]
            out.append(f"table {st}: not the rows' table (r3layout.ROW_SPEC): differs in {diff or 'its header or its job list'}")
    return out


def run(root):
    root = pathlib.Path(root)
    out = []
    binfo = json.loads((root / "bins" / "blobs.json").read_text())
    regs = fw.load_regs()
    for name in BLOBS:
        text = (root / "asm" / f"{name}.s").read_text()
        blob = (root / "bins" / f"{name}.blob").read_bytes()
        out += check_blob(name, text, blob, policy_of(name), regs)
        if sorted(binfo[name]["str"]) != sorted(L.STR_OF.get(name, [])):
            out.append(f"{name}: blobs.json str {binfo[name]['str']} is not {L.STR_OF.get(name, [])}")
        if bool(binfo[name].get("cont4")) != (name in L.CONT4_BLOBS):
            out.append(f"{name}: blobs.json cont4 flag is wrong")
    tabs = {st: json.loads((root / "tables" / f"{st}.json").read_text()) for st in ROWS}
    out += check_tables(tabs, binfo)
    return out


def main(argv):
    root = pathlib.Path(argv[argv.index("--root") + 1]) if "--root" in argv else R3
    problems = run(root)
    for p in problems:
        print("GUARD: " + p)
    if not problems:
        print(f"guard_blobs: clean ({len(BLOBS)} blobs, {len(ROWS)} tables)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
