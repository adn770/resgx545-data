"""gen_r4b.py: writes tables/fr.json, predictions/fr.tsv and TABLES.md from gen/r4blayout.py (the one source).  Run before the
freeze, never after the first job.  The blob is not generated: bins/ring_exit.blob, bins/blobs.json and asm/ring_exit.s are
R3k-events' frozen files byte for byte (tests/test_gen_r4b.py checks the hashes against the published freeze).

predictions/fr.tsv: `case quantity value model set`, one row per prediction.  Models: `control (E817 JOB)` for the controls
(values from E817's kept job of the same shape), `H-REP` (FCF's stop reproduces with E817's exact signature) and `H-NOREP`
(FCF keeps the tick: the stop does not repeat) for the three FCF replicates, `design` for what the task must do whatever
the hypothesis (the acted pass is taken and logged with its flag).
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
R4 = HERE.parent
sys.path.insert(0, str(HERE))
import r4blayout as L  # noqa: E402

STAGE = "fr"
RUNID0 = 0x7B00                     # run ids of the jobs (the page's RUNID; 32-bit, distinct from E817's 26625-26633)
GAP = f"{L.E817_KEPT_GAP[0]}..{L.E817_KEPT_GAP[1]}"
E0N = f"{L.E817_E0_ENTRIES[0]}..{L.E817_E0_ENTRIES[1]}"


def src_of(name):
    """The E817 job whose kept values a control of this shape is frozen from."""
    if name.startswith("fk"):
        return L.E817_AFTER_STOP
    return name[2:]                                   # b2fc4-r2 -> fc4-r2


def jobs():
    out, i = [], 0
    for row, spec in L.ROW_SPEC[STAGE].items():
        for k in range(spec["reps"]):
            j = {"name": L.rep_name(row, k), "row": row, "set": spec["label"] if k == 0 or spec["label"] == "control" else "replicate",
                 "op": "act", "kind": spec["kind"], "act": spec["act"], "count": spec["count"], "trigger": spec["trigger"], "window": 2,
                 "pre_ms": 3, "open_ms": spec["open_ms"], "d_reads": 20, "runid": RUNID0 + i, "may_stop": spec["may_stop"],
                 "block": spec["block"], "block_start": spec["block_start"] and k == 0}
            if spec.get("run_if"):
                j["run_if"] = spec["run_if"]
            out.append(j)
            i += 1
    return out


def table():
    i = L.STAGE_INFO[STAGE]
    return {"stage": STAGE, "session": "r4b", "blob": i["blob"], "arm": i["arm"], "stop_budget": i["budget"],
            "per_job_reset": i["per_job_reset"], "needs": None, "jobs": jobs()}


def preds():
    P = []

    def add(n, q, v, model, s):
        P.append((n, q, str(v), model, s))
    e = L.E817_FCF
    for j in jobs():
        n, row, s = j["name"], j["row"], j["set"]
        add(n, "arm_exit", hex(L.EXIT_INDEX), "design (E817 arm.json: exit 0x1974)", "control")
        if row.endswith("E0"):
            m = "control (E817 e0)"
            add(n, "acted", 0, m, s)
            add(n, "entries", E0N, m, s)
            add(n, "grid", "yes", m, s)
            continue
        add(n, "acted", 1, "design", s)
        add(n, "act_seen", j["act"], "design", s)
        add(n, "flag_logged", L.TAIL_FLAG if j["act"] == L.ACT_CONT4 else L.SKIP_FLAG, "design", s)
        if not row.startswith("FCF"):
            m = f"control (E817 {src_of(n)})"
            add(n, "kept", "yes", m, s)
            add(n, "next_gap", GAP, m, s)
            add(n, "read_minus_write", 0, m, s)
            add(n, "dword14", "0", m, s)
            continue
        # an FCF replicate: H-REP (E817's exact signature) against H-NOREP (the tick is kept)
        add(n, "kept", "no", "H-REP", s)
        add(n, "next_entry", "none", "H-REP", s)
        add(n, "clkstat", f"{e['clkstat']:#010x}", "H-REP", s)
        add(n, "event_status", f"{e['event_status']:#010x}", "H-REP", s)
        add(n, "sig_elements", "busy,serv_event_empty_clear,serv_event_frozen,timer_counting", "H-REP", s)
        add(n, "read_minus_write", e["read_minus_write"], "H-REP", s)
        add(n, "dword14", "0", "H-REP", s)
        add(n, "p3_answered", e["p3_answered"], "H-REP", s)
        add(n, "kept", "yes", "H-NOREP", s)
        add(n, "next_gap", GAP, "H-NOREP", s)
    return P


def tables_md(t, P):
    out = ["# R4b tables (generated by gen/gen_r4b.py; frozen)", "",
           f"Stage `fr`: blob `{t['blob']}`, arm `{t['arm']}`, three blocks; a reset and the arm at each block start only (and a "
           f"re-arm after a stop), stop budget {t['stop_budget']} (only FCF rows may stop; a stop in any other row ends the stage).", "",
           "| job | block | row | set | act | run_if | may stop | E817 job |", "|---|---|---|---|---|---|---|---|"]
    for j in t["jobs"]:
        out.append(f"| {j['name']}{' (reset, arm)' if j['block_start'] else ''} | {j['block']} | {j['row']} | {j['set']} | {j['act']} | "
                   f"{j.get('run_if', '-')} | {'yes' if j['may_stop'] else 'no'} | {'fcf' if j['row'].startswith('FCF') else src_of(j['name'])} |")
    out += ["", "## Predictions", "", "| case | quantity | value | model | set |", "|---|---|---|---|---|"]
    out += [f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in P]
    return "\n".join(out) + "\n"


def main():
    t = table()
    P = preds()
    (R4 / "tables").mkdir(exist_ok=True)
    (R4 / "predictions").mkdir(exist_ok=True)
    (R4 / "tables" / f"{STAGE}.json").write_text(json.dumps(t, indent=1, sort_keys=True) + "\n")
    (R4 / "predictions" / f"{STAGE}.tsv").write_text("case\tquantity\tvalue\tmodel\tset\n" + "".join("\t".join(r) + "\n" for r in P))
    (R4 / "TABLES.md").write_text(tables_md(t, P))
    print(f"{len(t['jobs'])} jobs, {len(P)} predictions")


if __name__ == "__main__":
    main()
