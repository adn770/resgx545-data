def tjob(name, sset, row, shape, kind, iters, **kw):
    j = {"name": name, "set": sset, "op": "probe", "row": row, "shape": shape, "kind": kind, "iters": iters,
         "prog": f"loop-{kind}-i{iters}", "knobs": {}, "runid": rid(), "tool_timeout_s": 60}
    if shape == "fill":
        j["tool_args"] = ["probe", f"$B/loop-{kind}-i{iters}.bin"]
    else:
        side = int(shape[3:])
        j["tool_args"] = ["probe", "--tri", "pixel", "--width", str(side), "--height", str(side),
                          f"$B/loop-{kind}-i{iters}.bin"]
    j.update(kw)
    return j


