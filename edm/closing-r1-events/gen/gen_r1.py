# ---- the ring task (S2's ring_e1, slot 3 at L.RUNGS[3] rungs) ------------------------------------------------------
HDR = """; SPDX-License-Identifier: MIT
; ring_e1.s -- generated by closing2/r1-events/gen/gen_r1.py (R1-events of the question-closing pass, PREPARED, NOT RUN)
; The event ring of S2 (closing/s2/asm/ring_e1.s, E746, E747) with slot 3 at 12 rungs; window 0 tail-calls at once,
; 1 logs all but plain ticks, 2 logs every pass.  Our own source, written from doc/specs/usse_isa.md and the records
; E146, E155, E532, E536, E538, E539; run as an EDM task from the page the kernel maps (index 0x4000); only forms the
; landed verifier accepts.  Registers r1-r18 and r22-r31 only.  No str, no emit, no lock, no clock-gate register, no
; sa write; every store the same value from every lane.
"""
TRIPLE = """t{k}:
        mov r30, #0xdeadbeef                ; @patch cont{k}
        mov pclink, r30
        lapc
"""


def ring_entry(k):
    base = L.RING_BASE[k] * 4
    a = [f"@entry {k}",
         "        mov r1, #0xdeadbeef                 ; @patch res+0",
         f"        mov r2, #0xdeadbeef                 ; @patch res+{base:#x}",
         "        mov r4, pa0",
         "        mov r5, pa1",
         "        mov r6, pa2",
         "        ldr r11, #81, drc0                  ; CR_TIMER at the pass's start",
         "        wdf drc0",
         f"        ldad.bypassl1 r3, [r1,+#{L.WINDOW}], drc0   ; the window",
         "        wdf drc0",
         "        and.testtanz.chan0 !c0, p0, r3, r3  ; p0 = window open",
         f"        !p0 br @x{k}",
         "        xor.testtaz.chan0 !c0, p1, r3, #2   ; p1 = window 2: every pass",
         f"        p1 br @s{k}_0",
         "        mov r9, #0x00ffffff",
         "        and.testtanz.chan0 !c0, p1, r5, r9  ; p1 = pa1[23:0] not 0 (31:24 is a count, S2 run 1)",
         f"        p1 br @s{k}_0",
         "        xor.testtanz.chan0 !c0, p1, r4, #2  ; p1 = pa0 is not 2",
         f"        p1 br @s{k}_0",
         f"        br @x{k}                             ; a plain tick in window 1: not logged"]
    n = L.RUNGS[k]
    for j in range(n):
        o = L.RUNG * j
        nxt = f"s{k}_{j + 1}" if j + 1 < n else f"full{k}"
        a += [f"s{k}_{j}:",
              f"        ldad.bypassl1 r7, [r2,+#{o}], drc0",
              "        wdf drc0",
              "        and.testtanz.chan0 !c0, p0, r7, r7  ; p0 = rung taken",
              f"        p0 br @{nxt}",
              "        mov r7, #0x00000001",
              f"        stad [r2,+#{o}], r7",
              f"        stad [r2,+#{o + 1}], r4",
              f"        stad [r2,+#{o + 2}], r5",
              f"        stad [r2,+#{o + 3}], r6",
              f"        stad [r2,+#{o + 4}], r11",
              "        idf drc0, bif",
              "        wdf drc0",
              f"        br @x{k}"]
    a += [f"full{k}:",
          f"        ldad.bypassl1 r8, [r1,+#{L.DROP + k}], drc0",
          "        wdf drc0",
          "        mov r9, #0xffffffff",
          "        ima32.u r8, r8, #1, r9.neg",
          f"        stad [r1,+#{L.DROP + k}], r8                 ; the ring is full: counted, not lost silently",
          "        idf drc0, bif",
          "        wdf drc0",
          f"        br @x{k}",
          f"x{k}:"]
    return "\n".join(a) + "\n" + TRIPLE.format(k=k)


def ring_source():
    return HDR + "\n" + "".join(ring_entry(k) for k in range(4))


def build_ring():
    regs = fwtask.load_regs()
    text = ring_source()
    (R1 / "asm" / "ring_e1.s").write_text(text)
    blob = fwtask.build_blob_text(text, regs)            # raises VerifyError if the verifier refuses
    (R1 / "bins" / "ring_e1.blob").write_bytes(blob)
    p = fwtask.parse_blob(blob)
    src = text.splitlines()
    return {"insns": len(p.words), "bytes": len(blob), "patches": len(p.patches), "entries": p.entries,
            "sha256": hashlib.sha256(blob).hexdigest(), "arm": ARM,
            "sa_writes": sorted({m.group(1) for ln in src for m in [re.match(r"\s+mov (sa\d+),", ln)] if m}),
            "str": sum(1 for ln in src if re.match(r"\s+str ", ln)),
            "rungs": dict(L.RUNGS)}


# ---- the Q082 loop programs ----------------------------------------------------------------------------------------
# Every loop is the shape of the landed int_loop.s (probes/platform/templates): phas, three movs, then BODY instructions
# ending in the counter's decrement with a test and the branch back to the body's first instruction, then o0 = counter.
# Body 8 is int_loop's (six integer multiply-adds, decrement, branch); body 16 has 14, body 4 two.  ld8 replaces two
# of the multiply-adds of body 8 by a load that bypasses the L1 cache and its wait: ldad + wdf + four multiply-adds +
# decrement + branch = 8 instructions, the load from the probe's scratch buffer (the SCRATCH_IMM immediate the tool
# patches).  The 4 multiply-adds of ld8 are r4..r7, the load's register r10.
MULADD_TEMPLATE = "imae.u r{d}, r3.low, r3.low, r3, u32"
HEAD = [";" + " SPDX-License-Identifier: MIT",
        "; {name}: ITER = {iters}, body {body} instructions ({what}); own source for Q082 (closing2/r1-events)",
        "phas #0, #0, pixel, end, parallel",
        "mov.skipinv r1, #{iters}",
        "mov.skipinv r2, #0xFFFFFFFF",
        "mov.skipinv r3, #0x00000003"]


def loop_source(kind, iters):
    kinds = {"b8": (8, 6, False), "b16": (16, 14, False), "b4": (4, 2, False), "ld8": (8, 4, True)}
    body, nmad, ld = kinds[kind]
    name = f"loop-{kind}-i{iters}"
    what = {"b8": "int_loop's", "b16": "fourteen multiply-adds", "b4": "two multiply-adds",
            "ld8": "ldad, wdf, four multiply-adds"}[kind]
    out = [ln.format(name=name, iters=iters, body=body, what=what) for ln in HEAD]
    if ld:
        out.append("mov.skipinv r29, #0x5CAF0000                     ; the scratch buffer's address (patched by the tool)")
    first = sum(1 for ln in out if not ln.startswith(";"))         # the body's first instruction (comments not counted)
    if ld:
        out += ["ldad.bypassl1 r10, [r29,+#0], drc0", "wdf drc0"]
    out += [MULADD_TEMPLATE.format(d=4 + i) for i in range(nmad)]
    out += ["iadd32.skipinv.testtanz.chan0 r1, p0, r1, r2", f"p0 ba #{first:#010x}", "mov.skipinv.end o0, r1"]
    n_body = sum(1 for ln in out if not ln.startswith(";")) - first - 1          # without the final mov.end
    assert n_body == body, (kind, n_body, body)
    return name, "\n".join(out) + "\n", first, body


def build_loop(kind, iters):
    name, text, first, body = loop_source(kind, iters)
    (R1 / "asm").mkdir(exist_ok=True)
    src = R1 / "asm" / f"{name}.s"
    src.write_text(text)
    out = R1 / "bins" / f"{name}.bin"
    subprocess.run([str(USSE_ASM), "-o", str(out), str(src)], check=True, capture_output=True)
    return name, {"kind": kind, "iters": iters, "body": body, "first": first, "prologue": first,
                  "sha256": hashlib.sha256(out.read_bytes()).hexdigest()}


