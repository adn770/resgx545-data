def tables_md(st, info, loops):
    out = ["# R1-events job tables (generated by gen/gen_r1.py; the JSON in tables/ is what runs)", "",
           f"Stages, in run order: {', '.join(STAGES)}.  Blob ring_e1: {info['insns']} instructions, {info['bytes']} bytes, "
           f"sha256 {info['sha256'][:16]}..., rungs {info['rungs']}, arm `{ARM}`, sa writes none, str {info['str']}.",
           f"Loop programs: {len(loops)} (bins/loop-*.bin, assembled by the landed usse-asm from asm/loop-*.s).", ""]
    for name in STAGES:
        s = st[name]
        out += ["", f"## {name}: {s['rows']} (blob {s['blob'] or 'none (stock firmware)'}, gate after: {s['gate'] or 'none'})", ""]
        out += ["| job | set | op | detail |", "|---|---|---|---|"]
        for j in s["jobs"]:
            if j["op"] == "k":
                d = (f"arm {j['arm_variant']}, pre {j['pre']}, window {j['window']}, trigger {j['trigger']}"
                     + (f" ({j['warm']} warm + {j['logged']} logged)" if j["trigger"] == "kicks" else ""))
            elif j["op"] == "probe":
                d = f"{j['row']} {j['shape']} {j['prog']} ({j['iters']} iterations)"
            elif j["op"] == "hold_fault":
                d = f"{j['row']} held TA fault (S3 recipe: hold_recovery Y, snaps at {j['snap1_s']} s and +{j['snap2_s']} s)"
            else:
                d = (f"window {j['window']}, tool {' '.join(j['tool_args'][:8])}, knobs {j['knobs'] or '-'}"
                     + (f", regtimeline {j['rt']}" if j.get("rt") else ""))
            out.append(f"| {j['name']} | {j['set']} | {j['op']} | {d} |")
    return "\n".join(out) + "\n"


def main():
    for d in ("asm", "bins", "tables", "predictions", "gates"):
        (R1 / d).mkdir(exist_ok=True)
    info = build_ring()
    loops = {}
    need = set()
    st = {"k": k_stage(), "t": t_stage(), "d0": d0_stage(), "d1": d1_stage()}
    for j in st["t"]["jobs"]:
        if j["op"] == "probe" and j["kind"] != "vtx":
            need.add((j["kind"], j["iters"]))
    for kind, it in sorted(need):
        nm, meta = build_loop(kind, it)
        loops[nm] = meta
    loops["vtx-stock"] = build_vtx()
    blobs = {"ring_e1": info, "loops": loops}
    (R1 / "bins" / "blobs.json").write_text(json.dumps(blobs, indent=1, sort_keys=True) + "\n")
    for name in STAGES:
        (R1 / "tables" / f"{name}.json").write_text(json.dumps(st[name], indent=1, sort_keys=True) + "\n")
    P = {"k": kpred(st["k"]), "t": tpred(st["t"]), "d0": dpred(st["d0"]), "d1": dpred(st["d1"])}
    for name in STAGES:
        rows = ["case\tquantity\tvalue\tmodel\tset"] + ["\t".join(r) for r in P[name]]
        (R1 / "predictions" / f"{name}.tsv").write_text("\n".join(rows) + "\n")
    (R1 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    (R1 / "TABLES.md").write_text(tables_md(st, info, loops))
    print(f"ring_e1: {info['insns']} insns, {info['bytes']} bytes, sha256 {info['sha256']}")
    print(f"{len(loops)} programs; jobs " + ", ".join(f"{k} {len(v['jobs'])}" for k, v in st.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
