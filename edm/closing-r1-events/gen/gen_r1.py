            P.append((n, "D5_bit3_pulses", "the EVENT_STATUS bit-3 rising pulses of the job's timeline = the ring's bit-19 "
                      "entries, in the same order among the other mapped bits (pa1 bit = 22 - status bit)",
                      "D5 (reversed order, E155/E747)", "heldout"))
