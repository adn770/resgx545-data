# Read-only register timelines around each kind of job: regtimeline (SGXFIVE_REGTIMELINE,
# default ~/regtimeline) samples the registers below while the job runs, from 50 ms before it,
# and prints the first sample and every change. The registers that move on their own (CR_TIMER,
# CR_EVENT_TIMER, CR_SETTLE_POLL0, CR_USE0_SERV_EVENT) and the ones whose read the kernel's
# register file skips (clears, kicks, starts, DPM tasks, PDS invalidates) are left out. Nothing
# is written but render_pb_pages, which the partial render sets and puts back.
set -u
T=${SGXFIVE_TEST:-$HOME/sgxfive-test}
RT=${SGXFIVE_REGTIMELINE:-$HOME/regtimeline}
D=$(sudo -n sh -c 'ls -d /sys/kernel/debug/dri/*/sgx' 2>/dev/null | head -n 1)
[ -x "$T" ] || { echo "no $T: build userspace/libsgxfive for the laptop first"; exit 1; }
[ -x "$RT" ] || { echo "no $RT: build tools/sweep/regtimeline.c on the laptop first"; exit 1; }
[ -n "$D" ] || { echo "no sgx debugfs directory (debug option off?)"; exit 1; }
echo "## uname"; uname -r
echo "## firmware"; sha256sum /lib/firmware/sgx545_ukernel.fw
echo "## module"; modinfo -F srcversion gma500_gfx 2>/dev/null
R="0x0000,0x0004,0x0008,0x001c,0x0020,0x0040,0x0044,0x0048,0x004c,0x0050,0x0054,0x0058"
