# one job: its name, then the command regtimeline runs (as root)
rt() {
	name=$1; shift
	echo "#### $name"
	sudo -n "$RT" 0 0.05 "$R" -- "$@" 2>&1
	echo "## $name: exit $?"
}
PB=$(sudo -n cat "$D/render_pb_pages")
echo "## render_pb_pages $PB"
for run in 1 2; do
	rt "fill-$run" cat "$D/xfer_fill"
	rt "copy-$run" cat "$D/xfer_copy"
	rt "tri-$run" "$T" tri
	rt "tri-two-renders-$run" "$T" tri -n 2
	rt "two-contexts-$run" "$T" contexts -n 2
	echo 0x30 | sudo -n tee "$D/render_pb_pages" >/dev/null
	rt "partial-1024x768-pb30-$run" "$T" tri --width 1024 --height 768
	echo "$PB" | sudo -n tee "$D/render_pb_pages" >/dev/null
	echo "## render_pb_pages back to $(sudo -n cat "$D/render_pb_pages")"
done
for size in 96x64 256x256 512x512 1024x768 1366x768 2048x2048 4096x4096; do
	rt "tri-$size" "$T" tri --width "${size%x*}" --height "${size#*x}"
done
echo "## status"; sudo -n cat "$D/status" | head -n 1
