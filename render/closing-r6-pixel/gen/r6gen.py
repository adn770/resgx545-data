"""r6gen.py: write everything R6-pixel runs from: tables/STAGE.txt, predictions/STAGE.tsv, bins/*.bin, TABLES.md, stages.txt.
Stages (plan closing6/pixel/exp-pixel-r6.md, DECISIONS-R6.md R6-2 a, order of plan section 6): p6-rd (58), p6-l3 (8), g6-rwa (8),
g6-rw (106), p6-s (22, last: the one kpoke).  202 jobs.
Run:  RESGX545_MAIN=<tree> PYTHONDONTWRITEBYTECODE=1 .../pixel-faults/.venv/bin/python gen/r6gen.py   (then run/freeze_r6.sh freeze)
"""
import collections
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import r5common as K  # noqa: E402
import r6_rd  # noqa: E402
import r6_rw  # noqa: E402

R6 = K.R5
STAGES = ["p6-rd", "p6-l3", "g6-rwa", "g6-rw", "p6-s"]


def rd_stage(fn):
    def f():
        b, head = fn()
        return b.rows, b.preds, list(dict.fromkeys(b.needs)), head, b.markers
    return f


BUILD = {"p6-rd": rd_stage(r6_rd.build_rd), "p6-l3": rd_stage(r6_rd.build_l3), "p6-s": rd_stage(r6_rd.build_s),
         "g6-rwa": lambda: r6_rw.build_stage("g6-rwa") + ({},), "g6-rw": lambda: r6_rw.build_stage("g6-rw") + ({},)}


def tables_md(st, rows, preds, head):
    by = collections.defaultdict(list)
    for p in preds:
        by[p[0]].append(p)
    out = [f"## {st}", "", "\n".join(head.strip().splitlines()), "", "| job | set | knobs | prediction rows |", "|---|---|---|---|"]
    for r in rows:
        ps = by.get(r.name, [])
        q = "; ".join(f"{p[1]} = {p[2]} [{p[3][:40]}]" for p in ps[:9]) + (f"; (+{len(ps) - 9} more)" if len(ps) > 9 else "")
        out.append(f"| {r.name} | {r.set} | {r.knobs} | {q or '-'} |")
    pseudo = sorted({p[0] for p in preds} - {r.name for r in rows})
    if pseudo:
        out += ["", "Pseudo-cases (read by the scorer):", ""]
        for n in pseudo:
            out += [f"- {n}: " + "; ".join(f"{p[1]} = {p[2]} ({p[4]})" for p in by[n][:8])
                    + (f"; (+{len(by[n]) - 8} more)" if len(by[n]) > 8 else "")]
    out += ["", "Row roles:", ""] + [f"- {r.name}: {r.role}" for r in rows] + [""]
    return "\n".join(out)


def main():
    K.BINS.mkdir(exist_ok=True)
    for f in K.BINS.glob("*"):
        f.unlink()
    md = ["# R6-pixel frozen tables (generated by gen/r6gen.py; the .txt tables and .tsv predictions are the frozen files)", "",
          "Sets: control, heldout, replicate, table.  Stage order: " + ", ".join(STAGES) + ".  Quantity = value [hypothesis].", ""]
    total, markers = 0, {}
    for st in STAGES:
        rows, preds, needs, head, mk = BUILD[st]()
        K.write_table(st, rows, needs, head)
        K.write_preds(st, preds)
        md.append(tables_md(st, rows, preds, head))
        markers.update(mk)
        total += len(rows)
        print(f"{st}: {len(rows)} jobs, {len(preds)} prediction rows, {len(needs)} programs")
    (K.BINS / "p6-markers.tsv").write_text("".join(f"{k}\t{v}\n" for k, v in markers.items()))
    (R6 / "TABLES.md").write_text("\n".join(md))
    (R6 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    print(f"total {total} jobs; {len(list(K.BINS.glob('*.bin')))} programs in bins/")


if __name__ == "__main__":
    main()
