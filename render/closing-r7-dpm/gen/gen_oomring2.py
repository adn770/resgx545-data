"""gen_oomring2.py: writes asm/oomring2.s and bins/oomring2.blob, the own firmware task of stage s-k (set B; plan closing7/b/
exp-dpm-r7.md sections 4 and 5, decision R7-4 (a)): R5-dpm's oomring (gen/gen_oomring.py source(), unchanged) plus, in each stub,
two read-only `ldr` of CR_DPM_PAGE_STATUS (0x0724, index 457) and CR_DPM_GLOBAL_PAGE_STATUS (0x072c, index 459), stored in each rung's
dwords 6 and 7 (the rung stride is 8 dwords; words 6 and 7 were unused).  No str, no sa or pa write.  R6-dpm's gen_oomring2.py
(closing6/r6-dpm), whose source both verifiers then refused, with only its header line and its outputs changed.

The register list that accepts it is round 7's (resgx545 7d0ee7f, regs.toml; fork 664fd0d0, sgx_own_regs.h: ldr of 7, 8, 81, 457,
459, 517, 670), built into module 37EC97AB; tests/test_oomring.py checks that the landed Python verifier at the frozen main and the
fork's own verifier at 664fd0d0 (host build) accept it, and that the OLD list (regs.toml before 7d0ee7f; the fork at 3f0b3e74, the
module 41E2F5C7 loaded now) refuses it: so s-k runs only after the one-shot boot of 37EC97AB, and its preflight checks the module.

    .../pixel-faults/.venv/bin/python gen/gen_oomring2.py      (writes asm/oomring2.s, bins/oomring2.blob, bins/blobs.json)
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import sys

KP = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(KP / "gen"))
import gen_oomring as G  # noqa: E402

fwtask = G.fwtask
LDR_PAGE, LDR_GLOBAL = 0x0724 // 4, 0x072C // 4      # 457, 459


def source(page=LDR_PAGE, glob=LDR_GLOBAL) -> str:
    src = G.source()
    head = "; oomring2.s -- generated by closing7/r7-dpm/gen/gen_oomring2.py (R7-dpm stage s-k, set B: round 7's register list):\n"
    src = src.replace(src.splitlines()[1] + "\n", head, 1)
    old = "        ldr r11, #81, drc0                  ; CR_TIMER\n        wdf drc0\n"
    new = old + (f"        ldr r14, #{page}, drc0                 ; CR_DPM_PAGE_STATUS (0x0724), read only\n        wdf drc0\n"
                 f"        ldr r15, #{glob}, drc0                 ; CR_DPM_GLOBAL_PAGE_STATUS (0x072c), read only\n        wdf drc0\n")
    assert src.count(old) == 4
    src = src.replace(old, new)
    out = []
    for ln in src.splitlines():
        out.append(ln)
        s = ln.strip()
        if s.startswith("stad [") and s.endswith("], r11"):          # after a rung's word 5 (the timer): words 6 and 7
            b, o = s[len("stad ["):].split(",+#")
            o = int(o.split("]")[0])
            out.append(f"        stad [{b},+#{o + 1}], r14")
            out.append(f"        stad [{b},+#{o + 2}], r15")
    return "\n".join(out) + "\n"


def main() -> int:
    src = source()
    (KP / "asm" / "oomring2.s").write_text(src)
    blob = fwtask.build_blob_text(src)
    (KP / "bins" / "oomring2.blob").write_bytes(blob)
    meta = json.loads((KP / "bins" / "blobs.json").read_text())
    p = fwtask.parse_blob(blob)
    meta["oomring2"] = {"arm": G.ARM, "bytes": len(blob), "insns": len(p.words), "entries": p.entries, "patches": len(p.patches),
                        "ring_at": G.RING_AT, "rungs": G.RUNGS, "mask": f"0x{G.MASK:08x}", "rung_words": "slot+1 pa0 pa1 sa8 sa9 "
                        "CR_TIMER 0x0724 0x072c", "sha256": hashlib.sha256(blob).hexdigest(),
                        "source_sha256": hashlib.sha256(src.encode()).hexdigest(),
                        "refusal_python": fwtask.refusal(blob, fwtask.load_regs()), "lint": fwtask.lint(src)}
    (KP / "bins" / "blobs.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n")
    print(json.dumps(meta["oomring2"], sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
