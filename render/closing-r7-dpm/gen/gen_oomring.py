"""gen_oomring.py: writes asm/oomring.s, the own firmware (EDM) task of stage A3 of R5-dpm (plan
closing5/dpm/exp-dpm-r5.md section 4, decision R5-5 (a)), and assembles it with the landed
tools/fwtask (bins/oomring.blob, bins/blobs.json).

What the task does, in each of the four stubs (PDS #13 slots 0 to 3):
  - counts its passes (results page dword 16 + slot);
  - when pa1 has any of bits 22, 21, 20, 10, 9 or 4 set (mask 0x00700610: the out-of-memory and
    end-of-render kinds the plan names), appends one rung to a 48-rung ring at res + 0x400
    (dword 256 + 8 j): [slot + 1, pa0, pa1, sa8, sa9, CR_TIMER]; a full ring counts the lost
    rungs in dword 20;
  - continues to the closed task of its slot (the patched continue triple), as events_m.s does.
Rules (HACKING.md "Firmware tasks of our own"): our own source, written from doc/specs/usse_isa.md,
asm/fwtask/events_m.s and closing4/r4-events/asm/ring_hold.s (the rung scan and the counter
idiom); r1-r13 and r30 only (bases r1, r2, r3, r6); no str, no sa write, no pa write, no emit, no lock, no clock-gate
register; ldr only of CR_TIMER (#81); every store the same value from every lane; every load and
store base a patched results-page limm.  Never made from the firmware image.
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import sys

KP = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, "/Users/jtorra/src/resgx545/tools/fwtask")
import fwtask  # noqa: E402

RUNGS = 48
RING_AT = 0x400            # byte offset of rung 0 in the results page
RUNG_WORDS = 8             # stride in dwords; words 0..5 used
MASK = (1 << 22) | (1 << 21) | (1 << 20) | (1 << 10) | (1 << 9) | (1 << 4)
PASS_DW = 16               # dword 16 + slot: passes of the slot
LOST_DW = 20               # dword 20: rungs lost to a full ring
PER_BASE = 16              # a stad/ldad offset is 0..127 dwords: 16 rungs a base register
BASES = ("r2", "r3", "r6")  # res + 0x400, + 0x600, + 0x800
ARM = "slots=0xf entry=0,1,2,3"

HEADER = f"""; SPDX-License-Identifier: MIT
; oomring.s -- generated by closing5/r5-dpm/gen/gen_oomring.py (R5-dpm stage A3, PREPARED, NOT RUN):
; four stubs count their passes and, when pa1 has any bit of 0x{MASK:08x} set, append
; [slot + 1, pa0, pa1, sa8, sa9, CR_TIMER] to a {RUNGS}-rung ring at res + 0x{RING_AT:x}; then each
; continues to the closed task of its slot.  Our own source, written from doc/specs/usse_isa.md,
; asm/fwtask/events_m.s and closing4/r4-events/asm/ring_hold.s; only forms the landed verifier
; accepts.  No str, no sa or pa write, no emit, no lock, no clock-gate register.
"""


def stub(k: int) -> list[str]:
    return [
        f"@entry {k}",
        "        mov r1, #0xdeadbeef                 ; @patch res+0",
        f"        mov r2, #0xdeadbeef                 ; @patch res+0x{RING_AT:x}",
        f"        mov r3, #0xdeadbeef                 ; @patch res+0x{RING_AT + 0x200:x}",
        f"        mov r6, #0xdeadbeef                 ; @patch res+0x{RING_AT + 0x400:x}",
        f"        mov r10, #0x{k + 1:08x}                 ; the slot tag of a rung",
        "        mov r4, pa0",
        "        mov r5, pa1",
        f"        ldad.bypassl1 r8, [r1,+#{PASS_DW + k}], drc0",
        "        wdf drc0",
        "        mov r9, #0xffffffff",
        "        ima32.u r8, r8, #1, r9.neg",
        f"        stad [r1,+#{PASS_DW + k}], r8                 ; passes of slot {k}",
        "        idf drc0, bif",
        "        wdf drc0",
        f"        mov r8, #0x{MASK:08x}",
        f"        and.testtanz.chan0 !c0, p0, r5, r8  ; p0 = pa1 & 0x{MASK:08x} != 0",
        f"        !p0 br @x{k}",
        "        mov r12, sa8",
        "        mov r13, sa9",
        "        ldr r11, #81, drc0                  ; CR_TIMER",
        "        wdf drc0",
        "        br @ring",
        f"x{k}:",
        f"        mov r30, #0xdeadbeef                ; @patch cont{k}",
        "        mov pclink, r30",
        "        lapc",
    ]


def ring() -> list[str]:
    out = ["ring:"]
    for j in range(RUNGS):
        b, o = BASES[j // PER_BASE], RUNG_WORDS * (j % PER_BASE)
        nxt = f"r{j + 1}" if j + 1 < RUNGS else "full"
        out += [
            f"r{j}:" if j else "",
            f"        ldad.bypassl1 r7, [{b},+#{o}], drc0",
            "        wdf drc0",
            "        and.testtanz.chan0 !c0, p0, r7, r7  ; p0 = rung taken",
            f"        p0 br @{nxt}",
            f"        stad [{b},+#{o}], r10",
            f"        stad [{b},+#{o + 1}], r4",
            f"        stad [{b},+#{o + 2}], r5",
            f"        stad [{b},+#{o + 3}], r12",
            f"        stad [{b},+#{o + 4}], r13",
            f"        stad [{b},+#{o + 5}], r11",
            "        idf drc0, bif",
            "        wdf drc0",
            "        br @done",
        ]
    out += [
        "full:",
        f"        ldad.bypassl1 r8, [r1,+#{LOST_DW}], drc0",
        "        wdf drc0",
        "        mov r9, #0xffffffff",
        "        ima32.u r8, r8, #1, r9.neg",
        f"        stad [r1,+#{LOST_DW}], r8                 ; rungs lost to a full ring",
        "        idf drc0, bif",
        "        wdf drc0",
        "done:",
        "        xor.testtaz.chan0 !c0, p1, r10, #1   ; p1 = slot 0",
        "        p1 br @x0",
        "        xor.testtaz.chan0 !c0, p1, r10, #2   ; p1 = slot 1",
        "        p1 br @x1",
        "        xor.testtaz.chan0 !c0, p1, r10, #3   ; p1 = slot 2",
        "        p1 br @x2",
        "        br @x3",
    ]
    return [ln for ln in out if ln != ""]


def source() -> str:
    lines = HEADER.rstrip("\n").splitlines() + [""]
    for k in range(4):
        lines += stub(k)
    lines += ring()
    return "\n".join(lines) + "\n"


def decode_ring(page: list[int]) -> dict:
    """The rungs and counters of a results page (1024 dwords): what the scorer reads."""
    base = RING_AT // 4
    rungs = []
    for j in range(RUNGS):
        w = page[base + RUNG_WORDS * j: base + RUNG_WORDS * j + 6]
        if not w or w[0] == 0:
            break
        rungs.append(dict(slot=w[0] - 1, pa0=w[1], pa1=w[2], sa8=w[3], sa9=w[4], timer=w[5]))
    return dict(passes=page[PASS_DW:PASS_DW + 4], lost=page[LOST_DW], rungs=rungs)


def main() -> int:
    src = source()
    (KP / "asm" / "oomring.s").write_text(src)
    blob = fwtask.build_blob_text(src)
    (KP / "bins" / "oomring.blob").write_bytes(blob)
    p = fwtask.parse_blob(blob)
    meta = {"oomring": {"arm": ARM, "bytes": len(blob), "insns": len(p.words), "entries": p.entries,
                        "patches": len(p.patches), "ring_at": RING_AT, "rungs": RUNGS, "mask": f"0x{MASK:08x}",
                        "sha256": hashlib.sha256(blob).hexdigest(),
                        "source_sha256": hashlib.sha256(src.encode()).hexdigest(),
                        "refusal_python": fwtask.refusal(blob, fwtask.load_regs()), "lint": fwtask.lint(src)}}
    (KP / "bins" / "blobs.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n")
    print(json.dumps(meta["oomring"], sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
