#!/usr/bin/env python3
"""Generate every S1b table, prediction file, staged program and TABLES.md.  Offline only.

  ~/src/scratch/resgx545/closing/pixel-faults/.venv/bin/python gen/s1gen.py

Writes tables/*.txt, predictions/*.tsv (+ p-b2-set-*.bits, p-d-A4.tsv), bins/*.bin, stages.txt, TABLES.md.
Row order in every table: plain rows (controls first), then the hypothesis rows (expected hangs and faults, knob
hypo:), whose controls come last; the runner refuses a plain row after a hypothesis row.
"""
from __future__ import annotations

import sys
sys.dont_write_bytecode = True     # imports the data repo's tex2/texmodel: no __pycache__ there (dataset digests)

import shlex  # noqa: E402
import textwrap  # noqa: E402

import s1common as C  # noqa: E402
from s1common import conditions, write_preds, write_table
import s1b_stages as B
import s1geo
import s1geo3

STAGES = ["p-b2", "g-e8b", "g-e1", "g-e3", "p-c", "g-e5", "p-d", "p-f", "g-e4w"]     # review order: no expected
#                                                                                     faults first, then p-d, p-f, g-e4w

# S1's post-hoc fits run again (S1b review): these jobs are `repeat`, never held out; the fitted model is renamed
# "(S1 post hoc)" where its name did not say so.  The scorers print repeat-only support apart.
REPEAT = {"p-f": ["f-dpm-dc0-r1", "f-dpm-dc0-r2"],
          "p-d": ["d-L2e2-64", "d-L3e3-64", "d-st-L3e2-64", "d-L2e2-21"],
          "p-c": [f"c-{c}-{a}" for c in ("k7", "k0", "k3", "g23") for a in "xy"],
          "g-e5": ["r-n8-a8-r1", "r-n8-a8-r2", "r-n8-a8-r3", "r-n8-a12-r1", "r-n8-a12-r2"],
          "p-b2": ["d-shift", "d-tall"],
          "g-e3": ["e3z-cut-p", "e3z-cut-m"]}
RENAME = {("p-f", "HI"): "HI (S1 post hoc: exact 2 of 2)", ("p-d", "HB-A4"): "HB-A4 (S1 post hoc: fit 4 of 4)"}


def as_repeat(st, rows, preds):
    names = set(REPEAT.get(st, ()))
    for r in rows:
        if r.name in names:
            r.set = "repeat"
            r.role = "REPEAT of an S1 post-hoc fit: " + r.role
    out = []
    for n, q, v, m, s in preds:
        if n in names:
            s, m = "repeat", RENAME.get((st, m), m)
        out.append((n, q, v, m, s))
    return rows, out


def wrap_cmd(cmd, width=92):
    toks = shlex.split(cmd, posix=False)
    lines, cur = [], ""
    for t in toks:
        if cur and len(cur) + 1 + len(t) > width:
            lines.append(cur + " \\")
            cur = "    " + t
        else:
            cur = (cur + " " + t) if cur else t
    return lines + [cur]


def order(rows):
    """Plain rows, controls first (stable); then hypothesis rows, the hypothesis controls last."""
    plain = [r for r in rows if "hypo:" not in r.knobs]
    hypo = [r for r in rows if "hypo:" in r.knobs]
    return ([r for r in plain if r.set == "control"] + [r for r in plain if r.set != "control"]
            + [r for r in hypo if r.set != "control"] + [r for r in hypo if r.set == "control"])


def main():
    C.BINS.mkdir(exist_ok=True)
    s1geo.build_green()
    s1geo3.build_red()
    s1geo.build_e5_programs()
    out = {"p-f": B.p_f(), "g-e4w": B.g_e4w(), "g-e5": B.g_e5()}
    rows, preds, needs, head, a4rows = B.p_d()
    out["p-d"] = (rows, preds, needs, head)
    out["p-b2"] = B.p_b2()
    out["g-e8b"] = B.g_e8b()
    out["g-e1"] = B.g_e1()
    out["g-e3"] = B.g_e3()
    out["p-c"] = B.p_c()
    (C.PREDS / "p-d-A4.tsv").write_text("job\tlabel\tpages\tpixels\n" + "".join(
        f"{n}\t{lab}\t{pg}\t{','.join(f'{v:08x}' for v in px)}\n" for n, lab, pg, px in a4rows))
    md = ["# S1b job tables (generated by gen/s1gen.py)", "",
          "Each job: name (set, render_pb_pages P, runner knobs, regtimeline), then the exact tool",
          "command.  The tool is `$T`, staged programs `$S`, the work directory `$W`.  `set`: control,",
          "heldout, replicate.  The table files in `tables/` are the runner's input; this is a view.", ""]
    total = 0
    for st in STAGES:
        rows, preds, need, head = out[st]
        rows, preds = as_repeat(st, rows, preds)
        out[st] = (rows, preds, need, head)
        rows = order(rows)
        write_table(st, rows, need, head)
        write_preds(st, preds)
        total += len(rows)
        md += [f"## {st}: {len(rows)} jobs, {conditions(rows)} conditions", "", "```"]
        md += [w for ln in head.strip().splitlines() for w in (textwrap.wrap(ln, 98) or [""])] + ["```", ""]
        for r in rows:
            tags = f"{r.set}, P={r.P}" + (f", knobs: {r.knobs}" if r.knobs else "") + ("" if r.rt == "-" else ", timeline")
            md += textwrap.wrap(f"- `{r.name}`: {r.role}.  [{tags}]", width=96, subsequent_indent="  ") + ["", "  ```"]
            md += ["  " + ln for ln in wrap_cmd(r.args)] + ["  ```", ""]
    (C.S1 / "TABLES.md").write_text("\n".join(md) + "\n")
    (C.S1 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    for st in STAGES:
        print(f"{st:6s} jobs {len(out[st][0]):3d} conditions {conditions(out[st][0]):3d}")
    print("total:", total)


if __name__ == "__main__":
    sys.exit(main())
