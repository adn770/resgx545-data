"""gen_oomring2.py: writes asm/oomring2.s, the task the plan asked for in stage r-k (closing6/dpm/exp-dpm-r6.md section 4, decision
5 (a)): R5-dpm's oomring (gen/gen_oomring.py, unchanged) plus two read-only `ldr` in each stub, of 0x0724 (CR_DPM_PAGE_STATUS,
index 457) and 0x072c (CR_DPM_GLOBAL_PAGE_STATUS, index 459), stored in each rung's dwords 6 and 7 (the rung stride is 8 dwords;
words 6 and 7 were unused).  No str, no sa or pa write.

It is NOT staged.  tests/test_oomring.py assembles it and asks both verifiers: the landed Python verifier (tools/fwtask, main d9b2969)
and the rgn4 module's own (the fork's sgxfive_owntask.c and sgx_fw.c at a2788bd86537, host build).  Both refuse the two ldr (neither
index is on the register list: regs.toml and the fork's sgx_own_regs.h allow ldr of 7, 8, 81, 517 and 670 only), and the same source
with the two indices replaced by #81 is accepted by both, so the ldr are the only refusal.  The plan's rule then applies: r-k runs
R5-dpm's oomring unchanged (bins/oomring.blob, sha256 5b2fcf02...), the count clauses are "cannot tell", and no kernel is built.

    .../pixel-faults/.venv/bin/python gen/gen_oomring2.py      (writes asm/oomring2.s only)
"""
from __future__ import annotations

import pathlib
import sys

KP = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(KP / "gen"))
import gen_oomring as G  # noqa: E402

LDR_PAGE, LDR_GLOBAL = 0x0724 // 4, 0x072C // 4      # 457, 459


def source(page=LDR_PAGE, glob=LDR_GLOBAL) -> str:
    src = G.source()
    head = "; oomring2.s -- generated by closing6/r6-dpm/gen/gen_oomring2.py (R6-dpm stage r-k, NOT STAGED: refused by both verifiers):\n"
    src = src.replace(src.splitlines()[1] + "\n", head, 1)
    old = "        ldr r11, #81, drc0                  ; CR_TIMER\n        wdf drc0\n"
    new = old + (f"        ldr r14, #{page}, drc0                 ; CR_DPM_PAGE_STATUS (0x0724), read only\n        wdf drc0\n"
                 f"        ldr r15, #{glob}, drc0                 ; CR_DPM_GLOBAL_PAGE_STATUS (0x072c), read only\n        wdf drc0\n")
    assert src.count(old) == 4
    src = src.replace(old, new)
    out = []
    for ln in src.splitlines():
        out.append(ln)
        s = ln.strip()
        if s.startswith("stad [") and s.endswith("], r11"):          # after a rung's word 5 (the timer): words 6 and 7
            b, o = s[len("stad ["):].split(",+#")
            o = int(o.split("]")[0])
            out.append(f"        stad [{b},+#{o + 1}], r14")
            out.append(f"        stad [{b},+#{o + 2}], r15")
    return "\n".join(out) + "\n"


def main() -> int:
    (KP / "asm" / "oomring2.s").write_text(source())
    print("asm/oomring2.s written (not staged)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
