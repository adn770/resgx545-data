"""r3gen.py: write everything R3-pixel runs from: tables/STAGE.txt, predictions/STAGE.tsv, bins/*.bin, TABLES.md, stages.txt,
conditional.txt.  R3-pixel is laptop session L2 of the question-closing pass, round 3 (decisions R3-P1 to R3-P10 in
plans/resgx545-question-closing.md; design closing3/pixel/exp-pixel-r3.md).  NOT RUN on the laptop.  Stage order (design section 5):
p-c3 (Q276, 75 jobs), q-f0 (10), q-f1a (54), q-f1b (54, the opposite order), q-t (93), q-v (88): 374 jobs.

Run with the scratch venv:  PYTHONDONTWRITEBYTECODE=1 .../pixel-faults/.venv/bin/python gen/r3gen.py   (then run/freeze_r3.sh freeze)
"""
import collections
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import r3_c  # noqa: E402
import r3_f  # noqa: E402
import r3_t  # noqa: E402
import r3_v  # noqa: E402
import r3common as K  # noqa: E402

R3 = K.R3
STAGES = ["p-c3", "q-f0", "q-f1a", "q-f1b", "q-t", "q-v"]
BUILD = {"p-c3": r3_c.c3, "q-f0": r3_f.f0, "q-f1a": lambda: r3_f.f1("a"), "q-f1b": lambda: r3_f.f1("b"), "q-t": r3_t.t, "q-v": r3_v.v}


def tables_md(st, rows, preds, head):
    by = collections.defaultdict(list)
    for p in preds:
        by[p[0]].append(p)
    out = [f"## {st}", "", "\n".join(head.strip().splitlines()), "", "| job | set | knobs | prediction rows |", "|---|---|---|---|"]
    for r in rows:
        ps = by.get(r.name, [])
        q = "; ".join(f"{p[1]} = {p[2]} [{p[3][:60]}]" for p in ps[:6]) + (f"; (+{len(ps) - 6} more)" if len(ps) > 6 else "")
        out.append(f"| {r.name} | {r.set} | {r.knobs} | {q or '-'} |")
    pseudo = sorted({p[0] for p in preds} - {r.name for r in rows})
    if pseudo:
        out += ["", "Pseudo-cases (frozen predictions of a ladder or of a pair of rows, read by the scorer):", ""]
        for n in pseudo:
            out += [f"- {n}: " + "; ".join(f"{p[1]} = {p[2]} [{p[3][:50]}] ({p[4]})" for p in by[n])]
    out += ["", "Row roles:", ""] + [f"- {r.name}: {r.role}" for r in rows] + [""]
    return "\n".join(out)


def main():
    K.BINS.mkdir(exist_ok=True)
    md = ["# R3-pixel frozen tables (generated by gen/r3gen.py; the .txt tables and .tsv predictions are the frozen files)", "",
          "Sets: control, heldout, repeat (CONFIRM rows of Q276, EVERY ROW READ POST HOC IN ROUND 2 and frozen now, and E769's refuted "
          "hypotheses: tallied apart), replicate.  Stage order: " + ", ".join(STAGES) + ".  Quantity = value [hypothesis].", ""]
    total = 0
    for st in STAGES:
        rows, preds, needs, head = BUILD[st]()
        K.write_table(st, rows, needs, head)
        K.write_preds(st, preds)
        md.append(tables_md(st, rows, preds, head))
        total += len(rows)
        print(f"{st}: {len(rows)} jobs, {len(preds)} prediction rows, {len(needs)} programs")
    (R3 / "TABLES.md").write_text("\n".join(md))
    (R3 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    (R3 / "conditional.txt").write_text("")
    print(f"total {total} jobs; {len(list(K.BINS.glob('*.bin')))} programs in bins/")


if __name__ == "__main__":
    main()
