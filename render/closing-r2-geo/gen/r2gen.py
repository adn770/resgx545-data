#!/usr/bin/env python3
"""Generate every R2 table, prediction file, staged program and TABLES.md.  Offline only.

  PYTHONDONTWRITEBYTECODE=1 ~/src/scratch/resgx545/closing/pixel-faults/.venv/bin/python gen/r2gen.py

Writes tables/*.txt, predictions/*.tsv, bins/*.bin, stages.txt, TABLES.md.  Row order in every table: controls first, then
the rest.  No row predicts a hang or a fault: every such line stops its stage (rc 3 "scene overflowed" is the normal class).
"""
from __future__ import annotations

import sys
sys.dont_write_bytecode = True     # imports the data repo's modules via probe: no __pycache__ there

import collections  # noqa: E402
import shlex  # noqa: E402
import textwrap  # noqa: E402

import r1_geo as G1  # noqa: E402
import r2_geo as G  # noqa: E402
import rcommon as C  # noqa: E402
from rcommon import conditions, write_preds, write_table  # noqa: E402

STAGES = ["g-t3", "g-t4", "g-t5v", "g-c3", "g-c2"]
EXTRA = ["g-c3f"]                                          # a table, not in the session order


def wrap_cmd(cmd, width=92):
    toks = shlex.split(cmd, posix=False)
    lines, cur = [], ""
    for t in toks:
        if cur and len(cur) + 1 + len(t) > width:
            lines.append(cur + " \\")
            cur = "    " + t
        else:
            cur = (cur + " " + t) if cur else t
    return lines + [cur]


def order(rows):
    return [r for r in rows if r.set == "control"] + [r for r in rows if r.set != "control"]


def main():
    C.BINS.mkdir(exist_ok=True)
    G1.build_green()
    out = {"g-t3": G.g_t3(), "g-t4": G.g_t4(), "g-t5v": G.g_t5v(), "g-c3": G.g_c3(), "g-c3f": G.g_c3f(), "g-c2": G.g_c2()}
    md = ["# R2 job tables (generated by gen/r2gen.py)", "",
          "Each job: name (set, render_pb_pages P, runner knobs, regtimeline), the exact tool command and the frozen",
          "predictions (quantity = value [hypothesis] label).  The tool is `$T` (~/sgxfive-test-r1), staged programs `$S`, the",
          "work directory `$W`.  `set`: control, heldout, repeat, replicate.  `tables/` is the runner's input; this is a view.",
          "Knobs: `s2` = read CR_EVENT_STATUS2 from the debugfs regs after the reset and after the job; `sweep:G` = the rest of",
          "group G is skipped once a post-job STATUS2 has bit 7 set; `kpoke` = the row pokes pb:11 (only that), `wd:S` = the",
          "runner's watchdog writes the kernel's debugfs reset S seconds after the tool started; every `tri` job carries",
          "`expectdiff`.", ""]
    total = 0
    for st in STAGES + EXTRA:
        rows, preds, need, head = out[st]
        rows = order(rows)
        write_table(st, rows, need, head)
        write_preds(st, preds)
        by = collections.defaultdict(list)
        for n, q, v, m, s in preds:
            by[n].append((q, v, m, s))
        if st not in EXTRA:
            total += len(rows)
        md += [f"## {st}: {len(rows)} jobs, {conditions(rows)} conditions" + (" (not in the session)" if st in EXTRA else ""),
               "", "```"]
        md += [w for ln in head.strip().splitlines() for w in (textwrap.wrap(ln, 98) or [""])] + ["```", ""]
        for r in rows:
            tags = f"{r.set}, P={r.P}" + (f", knobs: {r.knobs}" if r.knobs else "") + ("" if r.rt == "-" else ", timeline")
            md += textwrap.wrap(f"- `{r.name}`: {r.role}.  [{tags}]", width=96, subsequent_indent="  ") + ["", "  ```"]
            md += ["  " + ln for ln in wrap_cmd(r.args)] + ["  ```"]
            for q, v, m, s in by.get(r.name, []):
                if q in ("knob0624_first", "marker", "kicks_open"):
                    continue
                md += textwrap.wrap(f"  - frozen: {q} = {v}  [{m}] ({s})", width=96, subsequent_indent="      ")
            md += [""]
    (C.R1 / "TABLES.md").write_text("\n".join(md) + "\n")
    (C.R1 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    for st in STAGES + EXTRA:
        print(f"{st:6s} jobs {len(out[st][0]):3d} conditions {conditions(out[st][0]):3d} predictions {len(out[st][1]):4d}")
    print("total (session):", total)


if __name__ == "__main__":
    sys.exit(main())
