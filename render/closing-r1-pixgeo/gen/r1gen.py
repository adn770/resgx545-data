#!/usr/bin/env python3
"""Generate every R1 table, prediction file, staged program and TABLES.md.  Offline only.

  PYTHONDONTWRITEBYTECODE=1 ~/src/scratch/resgx545/closing/pixel-faults/.venv/bin/python gen/r1gen.py

Writes tables/*.txt, predictions/*.tsv, bins/*.bin, stages.txt, TABLES.md.  Row order in every table: controls first,
then the rest (no hypothesis rows: every R1 job is expected to complete; a hang or fault stops the stage).
"""
from __future__ import annotations

import sys
sys.dont_write_bytecode = True     # imports the data repo's modules via probe: no __pycache__ there

import collections  # noqa: E402
import shlex  # noqa: E402
import textwrap  # noqa: E402

import r1_geo as G  # noqa: E402
import r1_q276 as Q  # noqa: E402
import rcommon as C  # noqa: E402
from rcommon import conditions, write_preds, write_table  # noqa: E402

STAGES = ["p-c2", "g-u1", "g-c1", "g-t1", "g-t2", "g-t7", "g-u2", "g-t5", "g-t6"]
EXTRA = ["g-c1f"]                                          # the pause cells: a table, not in the session order


def wrap_cmd(cmd, width=92):
    toks = shlex.split(cmd, posix=False)
    lines, cur = [], ""
    for t in toks:
        if cur and len(cur) + 1 + len(t) > width:
            lines.append(cur + " \\")
            cur = "    " + t
        else:
            cur = (cur + " " + t) if cur else t
    return lines + [cur]


def order(rows):
    return [r for r in rows if r.set == "control"] + [r for r in rows if r.set != "control"]


def main():
    C.BINS.mkdir(exist_ok=True)
    G.build_green()
    out = {"p-c2": Q.p_c2(), "g-u1": G.g_u1(), "g-c1": G.g_c1(), "g-c1f": G.g_c1f(), "g-t1": G.g_t1(),
           "g-t2": G.g_t2(), "g-t7": G.g_t7(), "g-u2": G.g_u2(), "g-t5": G.g_t5(), "g-t6": G.g_t6()}
    md = ["# R1 job tables (generated by gen/r1gen.py)", "",
          "Each job: name (set, render_pb_pages P, runner knobs, regtimeline), the exact tool command and the frozen",
          "predictions (quantity = value [hypothesis] label).  The tool is `$T`, staged programs `$S`, the work",
          "directory `$W`.  `set`: control, heldout, repeat, replicate.  `tables/` is the runner's input; this is a view.",
          "Knobs: `trial072c:U` = a 0x072c trial job (U = the 0x0724 peak the gate expects); `s072c` = sample 0x072c only",
          "if the gate passed (run/lib_r1.sh); every `tri` job carries `expectdiff`.", ""]
    total = 0
    for st in STAGES + EXTRA:
        rows, preds, need, head = out[st]
        rows = order(rows)
        write_table(st, rows, need, head)
        write_preds(st, preds)
        by = collections.defaultdict(list)
        for n, q, v, m, s in preds:
            by[n].append((q, v, m, s))
        if st not in EXTRA:
            total += len(rows)
        md += [f"## {st}: {len(rows)} jobs, {conditions(rows)} conditions" + (" (pause cells, not in the session)"
                                                                           if st in EXTRA else ""), "", "```"]
        md += [w for ln in head.strip().splitlines() for w in (textwrap.wrap(ln, 98) or [""])] + ["```", ""]
        for r in rows:
            tags = f"{r.set}, P={r.P}" + (f", knobs: {r.knobs}" if r.knobs else "") + ("" if r.rt == "-" else ", timeline")
            md += textwrap.wrap(f"- `{r.name}`: {r.role}.  [{tags}]", width=96, subsequent_indent="  ") + ["", "  ```"]
            md += ["  " + ln for ln in wrap_cmd(r.args)] + ["  ```"]
            for q, v, m, s in by.get(r.name, []):
                if q in ("knob0624_first", "marker", "kicks_open"):
                    continue
                md += textwrap.wrap(f"  - frozen: {q} = {v}  [{m}] ({s})", width=96, subsequent_indent="      ")
            md += [""]
    (C.R1 / "TABLES.md").write_text("\n".join(md) + "\n")
    (C.R1 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    for st in STAGES + EXTRA:
        print(f"{st:6s} jobs {len(out[st][0]):3d} conditions {conditions(out[st][0]):3d} predictions {len(out[st][1]):4d}")
    print("total (session):", total)


if __name__ == "__main__":
    sys.exit(main())
