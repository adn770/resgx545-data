"""r4gen.py: write everything R4-pixel runs from: tables/STAGE.txt, predictions/STAGE.tsv, bins/*.bin, TABLES.md, stages.txt.
Every stage module gen/r4_X.py has build() -> (rows, preds, needs, head) (rows: r4common.Row; preds: (case, quantity, value, model,
set) tuples; needs: the $S/NAME.bin paths of the staged programs; head: the table's header text).
Run:  RESGX545_MAIN=<tree> PYTHONDONTWRITEBYTECODE=1 .../pixel-faults/.venv/bin/python gen/r4gen.py   (then run/freeze_r4.sh freeze)
"""
import collections
import importlib
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import r4common as K  # noqa: E402

R4 = K.R4
STAGES = ["p4-o4", "q4-v", "q4-f", "q4-t", "g4-rw"]
MODULES = {"p4-o4": "r4_o4", "q4-v": "r4_v", "q4-f": "r4_f", "q4-t": "r4_t", "g4-rw": "r4_rw"}


def tables_md(st, rows, preds, head):
    by = collections.defaultdict(list)
    for p in preds:
        by[p[0]].append(p)
    out = [f"## {st}", "", "\n".join(head.strip().splitlines()), "", "| job | set | knobs | prediction rows |", "|---|---|---|---|"]
    for r in rows:
        ps = by.get(r.name, [])
        q = "; ".join(f"{p[1]} = {p[2]} [{p[3][:60]}]" for p in ps[:6]) + (f"; (+{len(ps) - 6} more)" if len(ps) > 6 else "")
        out.append(f"| {r.name} | {r.set} | {r.knobs} | {q or '-'} |")
    pseudo = sorted({p[0] for p in preds} - {r.name for r in rows})
    if pseudo:
        out += ["", "Pseudo-cases (frozen predictions of a ladder, a pair or a table, read by the scorer):", ""]
        for n in pseudo:
            out += [f"- {n}: " + "; ".join(f"{p[1]} = {p[2]} [{p[3][:50]}] ({p[4]})" for p in by[n][:12])
                    + (f"; (+{len(by[n]) - 12} more)" if len(by[n]) > 12 else "")]
    out += ["", "Row roles:", ""] + [f"- {r.name}: {r.role}" for r in rows] + [""]
    return "\n".join(out)


def main():
    K.BINS.mkdir(exist_ok=True)
    md = ["# R4-pixel frozen tables (generated by gen/r4gen.py; the .txt tables and .tsv predictions are the frozen files)", "",
          "Sets: control, heldout, repeat, replicate.  Stage order: " + ", ".join(STAGES) + ".  Quantity = value [hypothesis].", ""]
    total = 0
    for st in STAGES:
        mod = importlib.import_module(MODULES[st])
        rows, preds, needs, head = mod.build()
        K.write_table(st, rows, needs, head)
        K.write_preds(st, preds)
        md.append(tables_md(st, rows, preds, head))
        total += len(rows)
        print(f"{st}: {len(rows)} jobs, {len(preds)} prediction rows, {len(needs)} programs")
    (R4 / "TABLES.md").write_text("\n".join(md))
    (R4 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    print(f"total {total} jobs; {len(list(K.BINS.glob('*.bin')))} programs in bins/")


if __name__ == "__main__":
    main()
