#!/usr/bin/env python3
"""Generate every S1 table, prediction file, staged program and TABLES.md.  Offline only.

  ~/src/scratch/resgx545/closing/pixel-faults/.venv/bin/python gen/s1gen.py

Writes tables/*.txt, predictions/*.tsv (+ p-b2-sets.npz), bins/*.bin, stages.txt, TABLES.md.
g-e2b is NOT written here: it needs the measured U (gen/gen_e2_boundary.py, the PAUSE of S1).
"""
from __future__ import annotations

import sys

import s1common as C
from s1common import Row, conditions, write_preds, write_table
import s1geo
import s1geo3
import s1pix

STAGES = ["g-e1", "g-e2a", "g-e2b", "g-e3", "g-e4", "g-e8", "g-e8b", "g-e5", "p-b1", "p-c", "p-g", "p-b2", "p-d", "p-f"]


def wrap_cmd(cmd, width=92):
    import shlex
    toks = shlex.split(cmd, posix=False)
    lines, cur = [], ""
    for t in toks:
        if cur and len(cur) + 1 + len(t) > width:
            lines.append(cur + " \\")
            cur = "    " + t
        else:
            cur = (cur + " " + t) if cur else t
    return lines + [cur]


def controls_first(rows):
    """Controls first, except those that fault by design (expectfault): they go last, nothing depends on them."""
    lead = [r for r in rows if r.set == "control" and "expectfault" not in r.knobs]
    tail = [r for r in rows if "expectfault" in r.knobs and r.set == "control"]
    mid = [r for r in rows if r not in lead and r not in tail]
    return lead + mid + tail


def main():
    C.BINS.mkdir(exist_ok=True)
    s1geo.build_green()
    s1geo3.build_red()
    s1geo.build_e5_programs()
    out = {}
    rows, preds, need, head = s1geo.e1()
    out["g-e1"] = (rows, preds, need, head)
    rows, preds, need, head, model = s1geo.e2a()
    out["g-e2a"] = (rows, preds, need or ["$S/p1139-green.bin"], head)
    out["g-e3"] = s1geo3.e3()
    out["g-e4"] = s1geo.e4()
    out["g-e8"] = s1geo.e8()
    out["g-e8b"] = s1geo3.e8b()
    out["g-e5"] = s1geo.e5()
    out["p-b1"] = s1pix.p_b1()
    out["p-c"] = s1pix.p_c()
    out["p-g"] = s1pix.p_g()
    out["p-b2"] = s1pix.p_b2()
    out["p-d"] = s1pix.p_d()
    out["p-f"] = s1pix.p_f()
    md = ["# S1 job tables (generated by gen/s1gen.py)", "",
          "Each job: name (set, render_pb_pages P, runner knobs, regtimeline), then the exact tool",
          "command.  The tool is `$T`, staged programs `$S`, the work directory `$W`.  `set`: control,",
          "heldout, replicate.  The table files in `tables/` are the runner's input; this is a view.", ""]
    total = 0
    for st in STAGES:
        if st == "g-e2b":
            md += ["## g-e2b (generated after the PAUSE)", "",
                   "Boundary jobs P = U + 0x22 - 1 and U + 0x22 for each of the six scenes of g-e2a, and",
                   "two partial-render count jobs; `gen/gen_e2_boundary.py U.json`.  14 jobs when the",
                   "count jobs separate the (k, s) pairs, else 12; not in the totals.", ""]
            continue
        rows, preds, need, head = out[st]
        rows = controls_first(rows)
        write_table(st, rows, need, head)
        write_preds(st, preds)
        total += len(rows)
        md += [f"## {st}: {len(rows)} jobs, {conditions(rows)} conditions", "", "```"] + [w for ln in head.strip().splitlines()
                                                                               for w in (__import__("textwrap").wrap(ln, 98) or [""])] + ["```", ""]
        for r in rows:
            tags = f"{r.set}, P={r.P}" + (f", knobs: {r.knobs}" if r.knobs else "") + ("" if r.rt == "-" else ", timeline")
            import textwrap
            md += textwrap.wrap(f"- `{r.name}`: {r.role}.  [{tags}]", width=96, subsequent_indent="  ") + ["", "  ```"]
            md += ["  " + ln for ln in wrap_cmd(r.args)] + ["  ```", ""]
    (C.S1 / "TABLES.md").write_text("\n".join(md) + "\n")
    (C.S1 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    summary = {st: (len(out[st][0]), conditions(out[st][0])) for st in out}
    for st, (n, c) in summary.items():
        print(f"{st:6s} jobs {n:3d} conditions {c:3d}")
    print("total (without g-e2b):", total)
    print("E2 fit:", s1geo.fit_u())


if __name__ == "__main__":
    sys.exit(main())
