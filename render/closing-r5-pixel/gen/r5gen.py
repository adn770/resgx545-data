"""r5gen.py: write everything R5-pixel runs from: tables/STAGE.txt, predictions/STAGE.tsv, bins/*.bin, TABLES.md, stages.txt.
Stages (plan closing5/pixel/exp-pixel-r5.md, decision R5-3 a): p5-o4 (58 jobs), then g5-rw as two job tables g5-rwa (12: controls
and the quarter jobs, gated) and g5-rw (36).  Each module's build_stage(stage) -> (rows, preds, needs, head).
Run:  RESGX545_MAIN=<tree> PYTHONDONTWRITEBYTECODE=1 .../pixel-faults/.venv/bin/python gen/r5gen.py   (then run/freeze_r5.sh freeze)
"""
import collections
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import r5common as K  # noqa: E402
import r5_o4  # noqa: E402
import r5_rw  # noqa: E402

R5 = K.R5
STAGES = ["p5-o4", "g5-rwa", "g5-rw"]
BUILD = {"p5-o4": r5_o4.build, "g5-rwa": lambda: r5_rw.build_stage("g5-rwa"), "g5-rw": lambda: r5_rw.build_stage("g5-rw")}


def tables_md(st, rows, preds, head):
    by = collections.defaultdict(list)
    for p in preds:
        by[p[0]].append(p)
    out = [f"## {st}", "", "\n".join(head.strip().splitlines()), "", "| job | set | knobs | prediction rows |", "|---|---|---|---|"]
    for r in rows:
        ps = by.get(r.name, [])
        q = "; ".join(f"{p[1]} = {p[2]} [{p[3][:40]}]" for p in ps[:9]) + (f"; (+{len(ps) - 9} more)" if len(ps) > 9 else "")
        out.append(f"| {r.name} | {r.set} | {r.knobs} | {q or '-'} |")
    pseudo = sorted({p[0] for p in preds} - {r.name for r in rows})
    if pseudo:
        out += ["", "Pseudo-cases (read by the scorer):", ""]
        for n in pseudo:
            out += [f"- {n}: " + "; ".join(f"{p[1]} = {p[2]} ({p[4]})" for p in by[n][:8])
                    + (f"; (+{len(by[n]) - 8} more)" if len(by[n]) > 8 else "")]
    out += ["", "Row roles:", ""] + [f"- {r.name}: {r.role}" for r in rows] + [""]
    return "\n".join(out)


def main():
    K.BINS.mkdir(exist_ok=True)
    md = ["# R5-pixel frozen tables (generated by gen/r5gen.py; the .txt tables and .tsv predictions are the frozen files)", "",
          "Sets: control, heldout, replicate, table.  Stage order: " + ", ".join(STAGES) + ".  Quantity = value [hypothesis].", ""]
    total = 0
    for st in STAGES:
        rows, preds, needs, head = BUILD[st]()
        K.write_table(st, rows, needs, head)
        K.write_preds(st, preds)
        md.append(tables_md(st, rows, preds, head))
        total += len(rows)
        print(f"{st}: {len(rows)} jobs, {len(preds)} prediction rows, {len(needs)} programs")
    (R5 / "TABLES.md").write_text("\n".join(md))
    (R5 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    print(f"total {total} jobs; {len(list(K.BINS.glob('*.bin')))} programs in bins/")


if __name__ == "__main__":
    main()
