#!/usr/bin/env python3
"""Generate every R3 table, prediction file, staged program and TABLES.md.  Offline only.

  PYTHONDONTWRITEBYTECODE=1 ~/src/scratch/resgx545/closing/pixel-faults/.venv/bin/python gen/r3gen.py

Writes tables/*.txt, predictions/*.tsv, bins/*.bin, stages.txt, TABLES.md.  Row order in every table: controls first, then the rest.
No row predicts a hang or a fault: every such line stops its stage (rc 3 "scene overflowed" is the normal class of the DPM jobs).
"""
from __future__ import annotations

import sys
sys.dont_write_bytecode = True

import collections  # noqa: E402
import shlex  # noqa: E402
import textwrap  # noqa: E402

import r1_geo as G1  # noqa: E402
import r3_geo as G  # noqa: E402
import rcommon as C  # noqa: E402
from rcommon import conditions, write_preds, write_table  # noqa: E402

STAGES = ["g-da", "g-db", "g-dc", "g-dd", "g-c4", "g-d36", "g-c6", "g-c5", "g-c7"]
BUILD = {"g-da": G.g_da, "g-db": G.g_db, "g-dc": G.g_dc, "g-dd": G.g_dd, "g-c4": G.g_c4, "g-d36": G.g_d36, "g-c6": G.g_c6,
         "g-c5": G.g_c5, "g-c7": G.g_c7}


def wrap_cmd(cmd, width=92):
    toks = shlex.split(cmd, posix=False)
    lines, cur = [], ""
    for t in toks:
        if cur and len(cur) + 1 + len(t) > width:
            lines.append(cur + " \\")
            cur = "    " + t
        else:
            cur = (cur + " " + t) if cur else t
    return lines + [cur]


def main():
    C.BINS.mkdir(exist_ok=True)
    G1.build_green()
    md = ["# R3 job tables (generated by gen/r3gen.py)", "",
          "Each job: name (set, render_pb_pages P, runner knobs, regtimeline), the exact tool command and the frozen",
          "predictions (quantity = value [hypothesis] label).  The tool is `$T` (~/sgxfive-test-r1), staged programs `$S`, the",
          "work directory `$W`.  `set`: control, heldout, repeat, replicate.  `tables/` is the runner's input; this is a view.",
          "P: a hex value (render_pb_pages), `-` (not touched), or a cell the RUNNER derives from kept output: `B:G` the midpoint of",
          "the bracket of group G, `L:G[:off]` / `F:G[:off]` the last raise / first silent thr0 of group G (+ off) + 0x22.",
          "Knobs: `ctl:R|N` = a control with its expected raise (a different reading stops the session), `obs:G` = the job's",
          "observation (raise, none, void) is recorded in group G, `cal:G` = a calibration (page need, partial renders recorded),",
          "`gate:N` = more than N partial renders at the calibration ends the stage, `fit:G` = the row is skipped if 2 thr0 is above",
          "the page need of the group's calibration (the second run cannot reach thr0).  Stage-level predictions (`@name`) have no job.", ""]
    total = 0
    counts = {}
    for st in STAGES:
        rows, preds, need, head = BUILD[st]()
        write_table(st, rows, need, head)
        write_preds(st, preds)
        counts[st] = (len(rows), conditions(rows), len(preds))
        total += len(rows)
        by = collections.defaultdict(list)
        for n, q, v, m, s in preds:
            by[n].append((q, v, m, s))
        md += [f"## {st}: {len(rows)} jobs, {conditions(rows)} conditions", "", "```"]
        md += [w for ln in head.strip().splitlines() for w in (textwrap.wrap(ln, 98) or [""])] + ["```", ""]
        for r in rows:
            tags = f"{r.set}, P={r.P}" + (f", knobs: {r.knobs}" if r.knobs else "") + ("" if r.rt == "-" else ", timeline")
            md += textwrap.wrap(f"- `{r.name}`: {r.role}.  [{tags}]", width=96, subsequent_indent="  ") + ["", "  ```"]
            md += ["  " + ln for ln in wrap_cmd(r.args)] + ["  ```"]
            for q, v, m, s in by.get(r.name, []):
                if q in ("knob0624_first", "frac", "word_down", "word_up", "cell"):
                    continue
                md += textwrap.wrap(f"  - frozen: {q} = {v}  [{m}] ({s})", width=96, subsequent_indent="      ")
            md += [""]
        for n in sorted(k for k in by if k.startswith("@")):
            for q, v, m, s in by[n]:
                md += textwrap.wrap(f"- stage-level {n}: {q} = {v}  [{m}] ({s})", width=96, subsequent_indent="    ")
            md += [""]
    (C.R1 / "TABLES.md").write_text("\n".join(md) + "\n")
    (C.R1 / "stages.txt").write_text("\n".join(STAGES) + "\n")
    for st in STAGES:
        print(f"{st:6s} jobs {counts[st][0]:3d} conditions {counts[st][1]:3d} predictions {counts[st][2]:4d}")
    print("total (session):", total)


if __name__ == "__main__":
    sys.exit(main())
