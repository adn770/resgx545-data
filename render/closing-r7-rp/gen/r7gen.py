#!/usr/bin/env python3
"""r7gen.py: write every r7-rp table, prediction and staged program by the areas' generators, then TABLES.md (the tables'
rows by stage, the job count) and check the session's invariants: every stage of stages.txt has a table and a predictions
file, row names are unique in the session, every `$S/NAME` a row names is a `#need` of its table and a file of bins/, every
tri row has expectdiff, and the job count is the plan's 143.
  PY gen/r7gen.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KP = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(KP, "score"))
AREAS = ("g_q287", "g_q291", "g_rd", "g_dump", "g_q086")
PLAN_JOBS = {"s0": 4, "q287": 25, "q291g": 1, "q291": 26, "p7-rdc": 14, "p7-rd": 34, "q293": 4, "q139": 24, "q086": 11}


def rows(stage):
    out = []
    with open(os.path.join(KP, "tables", stage + ".txt")) as f:
        for line in f:
            line = line.rstrip("\n")
            if line and not line.startswith("#"):
                out.append(line.split("|", 5))
    return out


def needs(stage):
    with open(os.path.join(KP, "tables", stage + ".txt")) as f:
        return [l.split()[1] for l in f if l.startswith("#need ")]


def main():
    import importlib
    for a in AREAS:
        importlib.import_module(a).write(KP)
    st = [l.strip() for l in open(os.path.join(KP, "stages.txt")) if l.strip()]
    bad = []
    names = {}
    md = ["# r7-rp tables (generated by gen/r7gen.py: do not edit)", ""]
    total = 0
    for s in st:
        if not os.path.exists(os.path.join(KP, "predictions", s + ".tsv")):
            bad.append("no predictions/%s.tsv" % s)
        rs = rows(s)
        nd = needs(s)
        if len(rs) != PLAN_JOBS[s]:
            bad.append("%s: %d rows, the plan has %d" % (s, len(rs), PLAN_JOBS[s]))
        total += len(rs)
        md += ["## %s (%d jobs)" % (s, len(rs)), "", "| name | set | risk | knobs | tool | command |", "|---|---|---|---|---|---|"]
        for r in rs:
            if len(r) != 6:
                bad.append("%s: a row without six fields: %s" % (s, r[0]))
                continue
            name, sset, risk, knobs, tool, args = r
            if name in names:
                bad.append("%s: %s is also a row of %s" % (s, name, names[name]))
            names[name] = s
            if args.startswith("tri ") and "expectdiff" not in knobs.split():
                bad.append("%s: tri row %s without expectdiff" % (s, name))
            for m in re.findall(r"\$S/([A-Za-z0-9_.+-]+)", args):
                if "$S/" + m not in nd:
                    bad.append("%s: %s names $S/%s, not a #need" % (s, name, m))
                if not os.path.exists(os.path.join(KP, "bins", m)):
                    bad.append("%s: %s names $S/%s, not in bins/" % (s, name, m))
            md.append("| %s | %s | %s | %s | %s | `%s` |" % (name, sset, risk, knobs, tool, args.replace("|", "\\|")))
        md.append("")
    md.insert(2, "%d jobs in %d stages (stages.txt order: %s)." % (total, len(st), ", ".join(st)))
    md.insert(3, "")
    with open(os.path.join(KP, "TABLES.md"), "w") as f:
        f.write("\n".join(md))
    if total != 143:
        bad.append("%d jobs, the plan has 143" % total)
    for b in bad:
        print("FAIL", b)
    print("r7gen: %d jobs, %d stages%s" % (total, len(st), "" if not bad else ", %d problems" % len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
